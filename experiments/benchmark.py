"""Code for sampling positive and negative example pairs from a corpus of documents, in
order to evaluate the performance of a fingerprint-based methods for text containment.

The examples are deliberately sampled to be "difficult":

1) The positive examples are generated by applying a series of random edits to a chunk
of text from a document, while ensuring that the edited text still contain a substantial
shared segment according to an oracle function. The edits include adding hyphenation,
changing casing, adding boilerplate segments, and switching normalisation of unicode
characters. The length of the chunk is drawn between the oracle threshold and a share of
the final query length (``max_fragment_share``, default one half); the edits are bounded
so that a longer chunk remains one long shared segment rather than being edited down to
the threshold, and so that at most a fraction ``max_word_edit_rate`` of the words of the
chunk are changed (the character-level oracle is lenient with casing and hyphenation,
which exact word-matching methods are not). If the edited text is shorter than a target
length, it is expanded by
concatenating random samples of text from the corpus before and after it, until the
target length is reached.

2) The negative examples are generated by randomly selecting a document and editing it
until it no longer shares any segment with the original according to the oracle
function, while retaining as much of the original wording as possible (so that the
negatives still share many n-grams with the original, but no long aligned segment). The
document is first permuted globally by shuffling a few large chunks, and a fixed fraction
of its chunks is paraphrased with a conservative prompt that keeps most of the words and
only restructures the sentences (this fraction controls how much of the original wording
the negatives retain). The document is then edited in rounds: all the regions that still
align with the original above the threshold are edited at once, by permuting them
(splitting them into chunks smaller than the threshold and shuffling the chunks) when they
are long enough, and by paraphrasing them with the LLM otherwise, first with the
conservative prompt and, if that does not reduce the alignment, with an aggressive prompt
that changes most of the words.

Usage
-----

A benchmark JSONL file (``text``, ``type`` and ``source_doc_id`` per line, half
positives and half negatives, as expected by ``experiments/eval.py``) is built from a
corpus in one call::

    python -c "import experiments.benchmark as b; b.build_benchmark(
        '/path/to/corpus_dir',              # corpus file(s): .jsonl, .jsonl.gz, .jsonl.zst
        'eval_data/outofcorpus_sample.jsonl',  # texts NOT in the corpus (pads the positives)
        'eval_data/benchmark.jsonl',
        nb_examples=2000, pos_sw_threshold=1000, neg_sw_threshold=100)"

Each step can also be run on its own (for instance to spread the LLM-based negatives
over several GPU jobs appending to the same file), using the same intermediate files:

    1. ``sample_corpus(corpus, nb_docs, 'corpus_sample.jsonl')``
    2. ``generate_negatives('corpus_sample.jsonl', 'negatives.jsonl', 1000, sw_threshold=100)``
    3. ``generate_positives('corpus_sample.jsonl', 'outofcorpus.jsonl', 'positives.jsonl',
       1000, sw_threshold=1000, target_length='negatives.jsonl', max_fragment_share=0.5)``
    4. ``merge_examples('positives.jsonl', 'negatives.jsonl', 'benchmark.jsonl', 2000)``

``build_benchmark`` is resumable: it reuses the intermediate files of its work directory
and only tops up the negatives / positives files to the required number of examples.
"""

