def build_benchmark(
    corpus: Union[str, Iterable[str]],
    out_of_corpus_sample: str,
    output_path: str,
    nb_examples: int = 2000,
    pos_sw_threshold: float = 1000,
    neg_sw_threshold: float = 100,
    nb_corpus_docs: int = 10_000,
    work_dir: Optional[str] = None,
    use_llm: bool = True,
    paraphrase_fraction: float = 0.5,
    seed: Optional[int] = None,
    min_doc_length: int = 1_200,
    max_doc_length: int = 15_000,
    max_fragment_share: Optional[float] = 0.5,
) -> str:
    """Build a benchmark JSONL file (nb_examples examples, half positives and half
    negatives) from a corpus in one call, chaining sample_corpus, generate_negatives,
    generate_positives and merge_examples.

    The intermediate files are written to work_dir (default: ``<output stem>_work/``
    next to output_path) and reused when present: the corpus sample is kept if it
    already has nb_corpus_docs documents, and the negatives / positives files are only
    topped up to the required number of examples.  A run can thus be interrupted and
    restarted, or complemented by other jobs appending to the same intermediate files
    with generate_negatives / generate_positives.

    Args:
        corpus: corpus file (.jsonl, .jsonl.gz, .jsonl.zst), directory of corpus files,
            or collection of files and directories (the indexed corpus).
        out_of_corpus_sample: JSONL file of documents not in the corpus, used to pad
            the positives.
        output_path: destination JSONL file of the benchmark.
        nb_examples: total number of examples (split 50/50).
        pos_sw_threshold: minimum Smith-Waterman score of the shared segment of the
            positives.
        neg_sw_threshold: Smith-Waterman score the negatives must stay below.
        nb_corpus_docs: size of the corpus sample the examples are generated from.
        work_dir: directory of the intermediate files.
        use_llm, paraphrase_fraction: see generate_negatives.
        seed: seed of the final sampling and shuffling.
        min_doc_length, max_doc_length: see sample_corpus.
        max_fragment_share: see generate_positives (None: fragments of about
            pos_sw_threshold characters only).

    The positives are padded to the median length of the negatives.  Returns
    output_path.
    """
    if work_dir is None:
        stem = os.path.splitext(os.path.abspath(output_path))[0]
        work_dir = f"{stem}_work"
    os.makedirs(work_dir, exist_ok=True)
    nb_neg = nb_examples // 2
    nb_pos = nb_examples - nb_neg

    corpus_sample = os.path.join(work_dir, "corpus_sample.jsonl")
    negatives_path = os.path.join(work_dir, f"negatives_sw{neg_sw_threshold:g}.jsonl")
    positives_path = os.path.join(work_dir, f"positives_sw{pos_sw_threshold:g}.jsonl")

    print(f"[1/4] Corpus sample: {corpus_sample}", flush=True)
    if count_lines(corpus_sample) >= nb_corpus_docs:
        print("      already present, skipping")
    else:
        sample_corpus(
            corpus=corpus, nb_docs=nb_corpus_docs, output_path=corpus_sample, min_length=min_doc_length, max_length=max_doc_length
        )

    print(f"[2/4] {nb_neg} negatives (SW < {neg_sw_threshold}): {negatives_path}", flush=True)
    generate_negatives(
        corpus_sample=corpus_sample, output_path=negatives_path, nb_examples=nb_neg, sw_threshold=neg_sw_threshold, use_llm=use_llm, paraphrase_fraction=paraphrase_fraction
    )
    print(f"[3/4] {nb_pos} positives (SW >= {pos_sw_threshold}): {positives_path}", flush=True)
    generate_positives(
        corpus_sample=corpus_sample,
        out_of_corpus_sample=out_of_corpus_sample,
        output_path=positives_path,
        nb_examples=nb_pos,
        sw_threshold=pos_sw_threshold,
        target_length=negatives_path,
        max_fragment_share=max_fragment_share,
    )

    print(f"[4/4] Merging into {output_path}", flush=True)
    return merge_examples(positives_path, negatives_path, output_path, nb_examples, seed)


class Corpus:
    """Corpus of documents which can be sampled."""

    def __init__(self, jsonl_path: Optional[str] = None):
        """Initialize the Corpus by loading documents from a JSONL file."""
        self.data = []
        if jsonl_path is not None:
            with open(jsonl_path, "r") as f:
                for line in f:
                    self.data.append(orjson.loads(line))

    def sample_doc(self, min_length: int = 1000, max_length: int = 50000):
        """Sample a document from the corpus that meets the minimum length
        requirement."""
        MAX_ATTEMPTS = 1000
        attempts = 0
        while attempts < MAX_ATTEMPTS:
            doc = np.random.choice(self.data)
            doc_text = doc["text"]
            if len(doc_text) >= min_length and len(doc_text) <= max_length:
                basic_doc = {
                    k: v
                    for k, v in doc.items()
                    if k not in {"seg_langs", "web-register", "doc_scores"}
                }
                return basic_doc
            attempts += 1
        raise RuntimeError(
            f"Could not find a document of at least {min_length} characters and at most {max_length} characters after {MAX_ATTEMPTS} attempts."
        )


class PositiveExampleGenerator:
    """Generator for positive example pairs (that is, pairs of texts which do contains a
    shared segment according to the oracle) from a corpus."""

    def __init__(
        self,
        corpus: Corpus,
        other_corpus: Optional[Corpus] = None,
        min_oracle_score: float = 1000,
        target_text_length: int = 2000,
        max_fragment_length: Optional[int] = None,
        max_score_loss: Optional[float] = None,
        max_word_edit_rate: float = 0.1,
    ):
        """Initialize the PositiveExampleGenerator with a hyphenation dictionary and an
        oracle.

        The shared fragment of a positive has a length drawn uniformly between
        min_oracle_score and max_fragment_length characters (None: fragments of about
        min_oracle_score characters, the hardest positives).  Whatever its length, the
        fragment is edited until its Smith-Waterman score with the source would fall
        below max(min_oracle_score, length - max_score_loss): max_score_loss (default:
        5 % of min_oracle_score) thus bounds the edit intensity of the fragment, so that
        longer fragments remain one long aligned segment instead of being edited down
        to the threshold.

        The character-level oracle charges little for a case flip or a hyphen, so that
        budget alone lets a large share of the words be altered, which destroys most
        word n-grams (and fingerprints) of the fragment.  Editing therefore also stops
        before more than a fraction max_word_edit_rate of the words of the fragment
        differ from the source (see word_edit_rate; default 0.1, the word-edit rate the
        detectors are calibrated for).  The edited fragment is padded with text from
        other_corpus up to target_text_length characters.
        """
        self.corpus = corpus
        if other_corpus is not None:
            self.other_corpus = other_corpus
        else:
            self.other_corpus = corpus
        self.dic = pyphen.Pyphen(lang="en")
        self.local_aligner = oracle.LocalAligner()
        self.min_oracle_score = min_oracle_score
        self.target_text_length = target_text_length
        if max_fragment_length is not None and max_fragment_length < min_oracle_score:
            raise ValueError("max_fragment_length must be at least min_oracle_score")
        self.max_fragment_length = max_fragment_length
        self.max_score_loss = (
            0.05 * min_oracle_score if max_score_loss is None else max_score_loss
        )
        if self.max_score_loss <= 0:
            raise ValueError("max_score_loss must be positive")
        if not 0.0 <= max_word_edit_rate <= 1.0:
            raise ValueError("max_word_edit_rate must be in [0, 1]")
        self.max_word_edit_rate = max_word_edit_rate

    def sample_positive(self) -> Optional[dict]:
        """Sample a positive example pair from the corpus.

        The method first samples a document from the corpus, then selects a random chunk
        of text from that document to edit (of a length drawn between min_oracle_score
        and max_fragment_length). It applies a series of random edits to the selected
        chunk, while ensuring that the edited text remains sufficiently similar to the
        original text according to an oracle function. In case the edited text is
        shorter than the target length, the method expands it by concatenating random
        samples of text from the corpus.

        Returns: A dictionary containing the original text, the edited text, their pair
        type (positive), the length of the fragment, and metadata about the source
        document and any documents used for expansion.
        """
        doc = self.corpus.sample_doc(int(self.min_oracle_score * 1.1), 50000)
        doc_text = doc["text"]

        # We select a random passage of the document to edit, whose length (at least
        # the minimum oracle score, so that a shared segment of that score fits in it)
        # is drawn uniformly up to max_fragment_length, within what the document can
        # provide.
        fragment_length = self._draw_fragment_length(len(doc_text))
        chunk_to_edit = self._select_fragment(doc_text, fragment_length)
        if chunk_to_edit is None:
            print("No suitable chunks found. Skipping.")
            return None

        doc_id = doc.get("u", doc.get("id", "unknown"))
        print(
            "Working on chunk from %s of length %i" % (doc_id, len(chunk_to_edit)),
            flush=True,
        )

        edited_text, region_score = self.edit_text(
            chunk_to_edit, min_region_score=self.min_region_score(len(chunk_to_edit))
        )
        if region_score < self.min_oracle_score:
            print("\nCould not edit text:", chunk_to_edit)
            print("Final score:", region_score)
            return

        meta_data = {k: v for k, v in doc.items() if k not in {"text"}}

        # If the edited text is shorter than the target length, we expand it by concatenating random
        # samples of text from the corpus before and after it, until the target length is reached.
        edited_fragment = edited_text
        edited_text, expansion_meta = self.expand_to_target_length(edited_text)

        result = {
            "text1": doc_text,
            "text2": edited_text,
            "pair_type": "positive",
            "score": region_score,
            "fragment_length": len(chunk_to_edit),
            "word_edit_rate": word_edit_rate(chunk_to_edit, edited_fragment),
            "meta": meta_data,
            **expansion_meta,
        }
        return result

    def _draw_fragment_length(self, doc_length: int) -> int:
        """Length of the fragment to edit from a document of doc_length characters:
        uniform between min_oracle_score and max_fragment_length, capped so that the
        fragment and its room for edits fit in the document."""
        lower = int(self.min_oracle_score)
        upper = lower if self.max_fragment_length is None else int(self.max_fragment_length)
        upper = min(upper, int(doc_length / 1.1))
        if upper <= lower:
            return lower
        return int(np.random.randint(lower, upper + 1))

    def min_region_score(self, fragment_length: int) -> float:
        """Smallest Smith-Waterman score the edited fragment must keep with its source:
        the oracle threshold, or fragment_length - max_score_loss for longer fragments."""
        return max(self.min_oracle_score, fragment_length - self.max_score_loss)

    def _select_fragment(self, text: str, fragment_length: int) -> Optional[str]:
        """Random passage of text of fragment_length characters, plus some room for the
        edits above the minimum region score (at least 10 characters, less than
        max_score_loss).

        The passage starts at a sentence boundary and ends at one when possible; when
        the last sentence would make it too long, only its beginning is taken, cut at a
        clause or word boundary.  Returns None if no passage fits (text too short, or
        a word longer than the room for edits at the cut)."""
        min_slack = min(10.0, self.max_score_loss / 2)
        min_length = fragment_length + min_slack
        max_length = fragment_length + self.max_score_loss
        sentences = split_units(text)
        # Sentences from which enough text follows (joined with single spaces)
        remaining = np.cumsum([len(s) + 1 for s in reversed(sentences)])[::-1] - 1
        starts = np.flatnonzero(remaining >= min_length)
        if len(starts) == 0:
            return None
        start = int(np.random.choice(starts))

        fragment = ""
        for sentence in sentences[start:]:
            candidate = f"{fragment} {sentence}" if fragment else sentence
            if len(candidate) < min_length:
                fragment = candidate
                continue
            if len(candidate) < max_length:
                return candidate
            # The sentence overshoots: cut it at a clause or word boundary instead
            for unit in split_units(sentence, max_unit_size=int(max_length - min_length)):
                fragment = f"{fragment} {unit}" if fragment else unit
                if len(fragment) >= min_length:
                    return fragment if len(fragment) < max_length else None
            return None
        return None

    def expand_to_target_length(self, text: str) -> Tuple[str, Dict[str, Any]]:
        """If the input text is shorter than the target length, expand it by
        concatenating random samples of text from the corpus before and after it, until
        the target length is reached.

        The method also returns metadata about the documents used for expansion.
        """
        meta_data = {"before": []}
        expanded_text = text

        # If the text is shorter than the target length, we add a preamble text from another document.
        while len(expanded_text) < self.target_text_length:
            nb_to_add = self.target_text_length - len(expanded_text)
            preamble_doc = self.other_corpus.sample_doc()
            preamble_text = preamble_doc["text"]
            if len(preamble_text) > nb_to_add:
                preamble_text = chunk_min(preamble_text, min_chunk_size=nb_to_add)[0]
            expanded_text = preamble_text + " " + expanded_text
            meta_data["before"].append(
                {"doc_id": preamble_doc["id"], "added": preamble_text}
            )
            print("Added preamble text of length %i" % len(preamble_text))

        return expanded_text, meta_data

    def edit_text(
        self,
        text,
        nb_attempts=500,
        timeout=300,
        min_region_score: Optional[float] = None,
    ) -> Tuple[str, float]:
        """Apply a series of random edits to the input text, while ensuring that the
        edited text remains sufficiently similar to the original text according to an
        oracle function.

        The edits include adding hyphenation, changing casing, adding boilerplate
        segments, and switching normalisation of unicode characters. The function
        returns the final edited text after applying a series of edits that are accepted
        by the oracle.  Edits are applied until one of them is rejected, either because
        the Smith-Waterman score of the largest aligned region drops below
        min_region_score, or because more than a fraction self.max_word_edit_rate of
        the words of the original text would differ (see word_edit_rate).

        Args:
            text: The input text to edit.
            nb_attempts: The maximum number of edit attempts to apply to the text.
            timeout: The maximum time in seconds to spend on editing the text.
            min_region_score: The Smith-Waterman score the largest aligned region must
                keep with the original text (default: self.min_oracle_score).

        Returns:
            A tuple containing the final edited text and its oracle score compared to the original text.

        """
        if min_region_score is None:
            min_region_score = self.min_oracle_score

        initial_text = str(text)
        successive_edits = []

        init_time = time.time()
        for _ in range(nb_attempts):
            if time.time() - init_time > timeout:
                break
            edit_functions = [
                self.add_hyphenation,
                self.change_casing,
                self.add_boilerplate_segment,
                self.switch_normalisation,
            ]
            chosen_edit_function = edit_functions[
                np.random.randint(len(edit_functions))
            ]
            edited_text = chosen_edit_function(text)
            if edited_text == text:
                continue

            print(".", end="", flush=True)
            # The word-level check is cheap, so the alignment is only computed for
            # edits that keep enough of the original words.
            accepted = (
                word_edit_rate(initial_text, edited_text) <= self.max_word_edit_rate
            )
            if accepted:
                region_score = self.local_aligner.get_largest_region_score(
                    initial_text, edited_text
                )
                accepted = region_score >= min_region_score

            if not accepted:
                if len(successive_edits) > 0:
                    print("OK", flush=True)
                    return successive_edits[-1]
                else:
                    continue

            successive_edits.append((edited_text, region_score))
            text = edited_text

        print("KO", flush=True)
        return initial_text, 0.0

    def add_hyphenation(self, text, nb_to_hyphenate=2) -> str:
        """Hyphenates a few words based on actual linguistic syllable boundaries."""
        words = text.split()

        # Shuffle words to avoid always picking the first eligible word
        indices = np.arange(len(words))
        np.random.shuffle(indices)

        hyphenated_words = 0
        for idx in indices:
            word = words[idx]

            # Strip punctuation for cleaner processing
            clean_word = word.strip('.,!?;:()"')
            if len(clean_word) < 5:  # Short words rarely wrap
                continue

            # Get hyphenation positions (e.g., 'hyphenation' -> 'hy-phen-ation')
            hyphenated_style = self.dic.inserted(clean_word)

            if "-" in hyphenated_style:
                # Choose a random hyphenation point provided by the dictionary
                parts = hyphenated_style.split("-")
                split_idx = np.random.randint(1, len(parts))

                head = "".join(parts[:split_idx])
                tail = "".join(parts[split_idx:])

                # Randomly decide whether to insert a newline after the hyphen to mimic line breaks in PDFs
                if random.random() > 0.5:
                    new_word = f"{head}-{tail}"
                else:
                    new_word = f"{head}-\n{tail}"

                # Replace only the specific instance of the word
                words[idx] = word.replace(clean_word, new_word)
                hyphenated_words += 1

                if hyphenated_words >= nb_to_hyphenate:
                    return " ".join(words)

        return text  # Return original if no suitable word found

    def change_casing(self, text, nb_to_change=3) -> str:
        """Randomly changes the casing of a few words in the text: titled words are
        lower-cased, lower-case words are upper-cased or titled.  Words with no
        changeable casing (all caps, digits, mixed case) are left alone, and the text is
        returned unchanged if it has none of the former."""
        words = text.split()
        candidates = [i for i, w in enumerate(words) if w.istitle() or w.islower()]
        if not candidates:
            return text
        np.random.shuffle(candidates)
        for idx in candidates[:nb_to_change]:
            word = words[idx]
            if word.istitle():
                words[idx] = word.lower()
            elif np.random.rand() < 0.5:
                words[idx] = word.upper()
            else:
                words[idx] = word.title()
        return " ".join(words)

    def add_boilerplate_segment(self, text) -> str:
        """Add a short boilerplate string at a random position in the text, to mimic
        text that could have been extracted from a PDF or a crawled web page."""
        segment = np.random.choice(BOILERPLATE_SEGMENTS)
        words = text.split()
        insert_idx = np.random.randint(0, len(words) + 1)
        words.insert(insert_idx, segment)
        return " ".join(words)

    def switch_normalisation(self, text) -> str:
        """Switch the normalisation of some unicode characters, such as changing
        straight quotes to curly quotes, or changing hyphens to en-dashes.

        Only reverse one type of character at a time.
        """
        transformations = [
            (r'"(.*?)"', r"“\1”"),  # Straight quotes to curly quotes
            (r"“(.*?)”", r'"\1"'),  # Curly quotes to straight quotes
            (r"'(.*?)'", r"‘\1’"),  # Straight single quotes to curly single quotes
            (r"‘(.*?)’", r"'\1'"),  # Curly single quotes to straight single quotes
            (r"'", r"’"),  # ASCII apostrophe to right single quotation mark
            (r"’", r"'"),  # Right single quotation mark to ASCII apostrophe
            (r"--", r"—"),  # Double hyphens to em-dash
            (r"—", r"--"),  # em-dash to double hyphens
            (r"-", r"–"),  # Hyphens to en-dash
            (r"–", r"-"),  # En-dash to hyphens
            (r"\.\.\.", r"…"),  # Three dots to ellipsis
            (r"…", r"..."),  # Ellipsis to three dots
            (r"fi", r"ﬁ"),  # fi ligature
            (r"ﬁ", r"fi"),  # fi ligature expanded
            (r"fl", r"ﬂ"),  # fl ligature
            (r"ﬂ", r"fl"),  # fl ligature expanded
            (r"\(c\)", "©"),  # Copyright symbol
            (r"©", "(c)"),  # Copyright symbol
            (r"\(r\)", "®"),  # Registered trademark symbol
            (r"®", "(r)"),  # Registered trademark symbol
            (r"\(tm\)", "™"),  # Trademark symbol
            (r"™", "(tm)"),  # Trademark symbol
        ]

        order = np.random.permutation(len(transformations))
        for idx in order:
            pattern, replacement = transformations[idx]
            matches = list(re.finditer(pattern, text))
            if not matches:
                continue

            match = matches[np.random.randint(len(matches))]
            replaced = re.sub(pattern, replacement, match.group(0), count=1)
            return text[: match.start()] + replaced + text[match.end() :]

        return text


class NegativeExampleGenerator:
    """Generator for negative example pairs (that is, pairs of texts which do not contain a
    shared segment according to the oracle) from a corpus."""

    def __init__(
        self,
        corpus: Corpus,
        llm_model: Optional[str] = "Qwen/Qwen2-7B-Instruct",
        min_oracle_score: float = 1000,
        permute_min_length: Optional[float] = None,
        max_chunk_size: int = 300,
        paraphrase_fraction: float = 0.5,
    ):
        """Initialize the NegativeExampleGenerator with a corpus and an LLM model.

        After the global permutation, a fraction paraphrase_fraction of the chunks of the
        document (of at most max_chunk_size characters) is paraphrased with the
        conservative prompt, which controls how much of the original wording the
        negatives retain (0: only the aligned regions are edited, 1: the whole document
        is paraphrased). Aligned regions of at least permute_min_length characters
        (default: 1.5 times min_oracle_score) are then permuted rather than paraphrased;
        paraphrases are done on windows of at most max_chunk_size characters."""
        if not 0.0 <= paraphrase_fraction <= 1.0:
            raise ValueError("paraphrase_fraction must be in [0, 1]")
        self.corpus = corpus
        if llm_model is None:
            self.model = None
        else:
            import vllm

            # All the regions edited in a round are paraphrased in one batch of short
            # chunks, so we let vLLM process many sequences at once
            self.model = vllm.LLM(
                model=llm_model,
                max_num_batched_tokens=8192,
                max_model_len=3000,
                max_num_seqs=64,
                gpu_memory_utilization=0.80,
                tensor_parallel_size=1,
            )
        self.aligner = oracle.LocalAligner()
        self.min_oracle_score = min_oracle_score
        self.permute_min_length = (
            1.5 * min_oracle_score if permute_min_length is None else permute_min_length
        )
        self.max_chunk_size = max_chunk_size
        self.paraphrase_fraction = paraphrase_fraction

    def sample_negative(
        self, max_nb_attempts: int = 50, max_regions_per_step: int = 16
    ) -> dict:
        """Sample a negative example from the corpus by randomly selecting a document
        and editing it so that it no longer shares any segment with the original
        according to the oracle function, while keeping as much of the original wording
        as possible.

        The document is first permuted globally (a few large chunks are shuffled) and a
        fraction self.paraphrase_fraction of its chunks is paraphrased with the
        conservative prompt. It is then edited in rounds: all the regions that still
        align with the original above the threshold (up to max_regions_per_step) are
        edited at once by _edit_regions, which permutes the long regions and paraphrases
        the short ones. A round is skipped if it increases the largest alignment score;
        after 2 consecutive skips the edit windows are randomised, and after 4 a
        boilerplate segment is inserted in the largest aligned region.

        Returns: A dictionary containing the original text, the edited text, their pair
        type (negative), the word n-gram overlap between the two texts, the number of
        steps and of applied edits per operation, and metadata about the example.
        """
        # We sample a document from the corpus that is long enough to allow for editing
        # but not too long to avoid excessively long processing times.
        doc = self.corpus.sample_doc(int(self.min_oracle_score * 2.0), 30000)
        source = self._normalise(str(doc["text"]))
        print("Working on text", doc["id"], flush=True)

        def find_regions(text: str) -> List[Tuple[int, int, float]]:
            return self._get_regions_to_edit(
                source, text, self.min_oracle_score, max_regions_per_step
            )

        print("STEP 1: global permutation and partial paraphrase of the document", flush=True)
        text = self._normalise(self.permute_chunks(source))
        text, nb_paraphrased = self._paraphrase_fraction(text)
        regions = find_regions(text)
        operations = collections.Counter(permute=1, paraphrase=nb_paraphrased)

        nb_skips = 0
        nb_steps = 1
        for step_nr in range(2, max_nb_attempts + 1):
            if not regions:
                break
            nb_steps = step_nr
            score = regions[0][2]
            print(
                "STEP %i: %i region(s) above threshold, scores: %s"
                % (step_nr, len(regions), [round(r[2]) for r in regions]),
                flush=True,
            )

            # If several consecutive rounds made no progress, the largest region is
            # probably resistant to edits (e.g. a flattened table or a long URL), so we
            # mechanically break it by inserting a boilerplate segment inside it.
            if nb_skips >= 3:
                print("WARNING: too many consecutive skips, inserting boilerplate")
                text = self._normalise(self._insert_boilerplate(text, *regions[0][:2]))
                regions = find_regions(text)
                nb_skips = 0
                continue

            edits = self._edit_regions(source, text, regions, stuck=nb_skips >= 2)
            if not edits:
                print("WARNING: no effective edit could be applied, skipping step")
                nb_skips += 1
                continue

            new_text = self._apply_edits(text, edits)
            new_regions = find_regions(new_text)
            new_score = new_regions[0][2] if new_regions else 0.0
            print("==> Region score after edit: %.1f" % new_score)
            if new_score > score:
                print("WARNING: region score increased after edit, skipping step")
                nb_skips += 1
                continue

            # An edit leaving the score unchanged is kept (it typically broke a region
            # tied with another one, e.g. a header repeated on every page) but still
            # counts as a round without progress.
            nb_skips = 0 if new_score < score else nb_skips + 1
            text, regions = new_text, new_regions
            operations.update(edit["operation"] for edit in edits)

        if regions:
            raise RuntimeError(
                "Example pair still above threshold after %i editing attempts, aborting."
                % max_nb_attempts
            )

        ngram_overlap = word_ngram_overlap(source, text)
        print(
            "Finished editing doc %s in %i steps: %s. Word 5-gram overlap: %.2f"
            % (doc["id"], nb_steps, dict(operations), ngram_overlap)
        )
        return {
            "text1": str(doc["text"]),
            "text2": text,
            "pair_type": "negative",
            "score": self.aligner.get_largest_region_score(source, text),
            "ngram_overlap": ngram_overlap,
            "nb_steps": nb_steps,
            "operations": dict(operations),
            "meta": {k: v for k, v in doc.items() if k not in {"text"}},
        }

    def _paraphrase_fraction(self, text: str) -> Tuple[str, int]:
        """Paraphrase a random fraction self.paraphrase_fraction of the chunks of the
        text (of at most self.max_chunk_size characters) with the conservative prompt,
        in a single LLM batch. Return the new text and the number of paraphrased chunks
        (0 if there is no LLM)."""
        chunks = chunk_max(text, max_chunk_size=self.max_chunk_size)
        nb_to_paraphrase = round(self.paraphrase_fraction * len(chunks))
        if self.model is None or nb_to_paraphrase == 0:
            return text, 0
        indices = sorted(np.random.choice(len(chunks), nb_to_paraphrase, replace=False))
        print("Paraphrasing %i of %i chunks" % (nb_to_paraphrase, len(chunks)))
        paraphrases = self.get_paraphrases(
            [chunks[i] for i in indices], temperature=0.8, style="conservative"
        )
        for i, paraphrase in zip(indices, paraphrases):
            chunks[i] = paraphrase
        return self._normalise(" ".join(chunks)), nb_to_paraphrase

    def _edit_regions(
        self,
        source: str,
        text: str,
        regions: List[Tuple[int, int, float]],
        stuck: bool = False,
    ) -> List[Dict[str, Any]]:
        """Edit all the given aligned regions of the text at once and return the edits
        (dicts with start, end, edited, operation) which reduce the alignment of their
        window with the source text.

        Regions of at least self.permute_min_length characters are permuted (split into
        chunks clearly smaller than the oracle threshold, whose order is shuffled); the
        shorter ones are paraphrased by the LLM in a single batch, first with the
        conservative prompt (which keeps most of the words), and, for the windows whose
        alignment did not decrease, again with the aggressive prompt. Without an LLM, all
        regions are permuted. When stuck, the windows are randomised and the paraphrases
        sampled at a higher temperature.
        """
        windows = self._select_windows(text, regions, stuck)
        edits = [
            {"start": start, "end": end, "original": text[start:end], "operation": op}
            for start, end, op in windows
        ]
        for edit in edits:
            print("%s of region [%i:%i]" % (edit["operation"], edit["start"], edit["end"]))

        # Permutations are done locally, paraphrases in one LLM batch
        permutations = [e for e in edits if e["operation"] == "permute"]
        paraphrases = [e for e in edits if e["operation"] == "paraphrase"]
        for edit in permutations:
            edit["edited"] = self.permute_chunks(
                edit["original"],
                target_chunk_size=0.7 * self.min_oracle_score,
                reference=source,
            )
        self._paraphrase_edits(paraphrases, "conservative", temperature=1.0 if stuck else 0.8)
        applied, rejected = self._check_edits(source, edits)

        # The windows whose conservative paraphrase did not reduce the alignment are
        # paraphrased again, right away, with the aggressive prompt
        retried = [e for e in rejected if e["operation"] == "paraphrase"]
        if retried:
            print("Retrying %i region(s) with the aggressive prompt" % len(retried))
            for edit in retried:
                edit["operation"] = "paraphrase_aggressive"
            self._paraphrase_edits(retried, "aggressive", temperature=1.0)
            applied += self._check_edits(source, retried)[0]
        return applied

    def _select_windows(
        self, text: str, regions: List[Tuple[int, int, float]], stuck: bool
    ) -> List[Tuple[int, int, str]]:
        """Choose, for each aligned region, the operation to apply and the window of the
        text to apply it on, as a list of non-overlapping (start, end, operation) tuples.

        Permuted regions are edited over their whole span, paraphrased ones over a window
        of at most self.max_chunk_size characters. When stuck, random sub-windows are used
        instead to break the deterministic choice of edit windows.
        """
        windows = []
        for start, end, _ in regions:
            length = end - start
            if self.model is None or length >= self.permute_min_length:
                operation, window_size = "permute", None
            else:
                operation, window_size = "paraphrase", self.max_chunk_size
            if stuck and length > 60:
                window_size = np.random.randint(max(30, length // 4), length)
            windows.append(
                (*self._select_window(text, start, end, window_size), operation)
            )
        return self._merge_windows(windows)

    def _paraphrase_edits(
        self, edits: List[Dict[str, Any]], style: str, temperature: float
    ) -> None:
        """Set the "edited" field of each edit to the paraphrase of its original text.
        The texts are split into chunks of at most self.max_chunk_size characters, which
        are all sent to the LLM in a single batch."""
        chunks_per_edit = [
            chunk_max(edit["original"], max_chunk_size=self.max_chunk_size)
            for edit in edits
        ]
        paraphrases = self.get_paraphrases(
            [c for chunks in chunks_per_edit for c in chunks], temperature, style
        )
        offset = 0
        for edit, chunks in zip(edits, chunks_per_edit):
            edit["edited"] = " ".join(paraphrases[offset : offset + len(chunks)])
            offset += len(chunks)

    @classmethod
    def _apply_edits(cls, text: str, edits: List[Dict[str, Any]]) -> str:
        """Replace the window of each edit by its edited text (from the last to the
        first, so that the offsets of the remaining windows stay valid)."""
        for edit in sorted(edits, key=lambda e: e["start"], reverse=True):
            text = (
                text[: edit["start"]] + " " + edit["edited"] + " " + text[edit["end"] :]
            )
        return cls._normalise(text)

    @staticmethod
    def _normalise(text: str) -> str:
        """Collapse all whitespace (including line breaks) into single spaces."""
        return re.sub(r"\s+", " ", text).strip()

    def _check_edits(
        self, initial_text: str, edits: List[Dict[str, Any]]
    ) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        """Split the edits into those which reduce the alignment of their window with the
        initial text (to be applied) and those which do not (to be dropped or retried)."""
        applied, rejected = [], []
        for edit in edits:
            score_before = self.aligner.get_largest_region_score(
                initial_text, edit["original"]
            )
            score_after = self.aligner.get_largest_region_score(
                initial_text, edit["edited"]
            )
            if score_after < score_before:
                applied.append(edit)
            else:
                print(
                    "WARNING: %s of region [%i:%i] did not reduce its score (%.1f -> %.1f)"
                    % (
                        edit["operation"],
                        edit["start"],
                        edit["end"],
                        score_before,
                        score_after,
                    )
                )
                rejected.append(edit)
        return applied, rejected

    @staticmethod
    def _insert_boilerplate(text: str, region_start: int, region_end: int) -> str:
        """Insert a random boilerplate segment at a word boundary chosen at random within
        the region [region_start:region_end] of the text. If the region contains no word
        boundary (e.g. a long URL or formula), the segment is inserted after a punctuation
        character inside the region, or at a random position as a last resort."""
        segment_to_insert = np.random.choice(BOILERPLATE_SEGMENTS)
        insertion_point = np.random.randint(region_start, max(region_end, region_start + 1))
        space_point = text.find(" ", insertion_point, region_end)
        if space_point != -1:
            insertion_point = space_point
        else:
            m = re.search(r"[./_\-=&?,;:)\]]", text[insertion_point:region_end])
            if m:
                insertion_point = insertion_point + m.end()
        return text[:insertion_point] + " " + segment_to_insert + " " + text[insertion_point:]

    def _top_region(self, initial_text: str, edited_text: str) -> Tuple[float, int, int]:
        """Return (score, start, end) of the region of the edited text that best aligns
        with the initial text, or (0.0, 0, 0) if there is no aligned region."""
        alignment_result = self.aligner.run(initial_text, edited_text)
        if not alignment_result.regions:
            return (0.0, 0, 0)
        largest_region = max(alignment_result.regions, key=lambda r: r["score"])
        return (largest_region["score"], largest_region["start2"], largest_region["end2"])

    def _get_regions_to_edit(
        self,
        initial_text: str,
        edited_text: str,
        min_score: float,
        max_regions: int = 16,
    ) -> List[Tuple[int, int, float]]:
        """Identify the regions of the edited text that need to be edited: up to
        max_regions non-overlapping regions which align with the initial text with a
        score of at least min_score, as a list of (start, end, score) tuples sorted by
        decreasing score. The windows actually edited are then derived from these
        regions with _select_window (which expands them to sentence boundaries).

        The aligner only returns the single best local alignment, so we iteratively cut
        the best region out of the edited text (keeping a map back to the original
        offsets) and re-run the alignment on the remainder.
        """
        masked_text = edited_text
        offset_map = np.arange(len(edited_text))
        separator_map = np.full(len(_MASK_SEPARATOR), -1)
        regions: List[Tuple[int, int, float]] = []
        while len(regions) < max_regions:
            score, start, end = self._top_region(initial_text, masked_text)
            if score < min_score or end <= start:
                break
            original_offsets = offset_map[start:end]
            original_offsets = original_offsets[original_offsets >= 0]
            if len(original_offsets) == 0:
                break
            regions.append(
                (int(original_offsets[0]), int(original_offsets[-1]) + 1, score)
            )
            masked_text = masked_text[:start] + _MASK_SEPARATOR + masked_text[end:]
            offset_map = np.concatenate(
                (offset_map[:start], separator_map, offset_map[end:])
            )
        return regions

    def _select_window(
        self,
        text: str,
        region_start: int,
        region_end: int,
        max_chunk_size: Optional[int] = None,
    ) -> Tuple[int, int]:
        """Select a window to edit inside the aligned region [region_start:region_end]: the
        full region if it fits in max_chunk_size (or if no size is given), otherwise a
        random sub-window of max_chunk_size characters. The window is then expanded
        outward to sentence boundaries."""
        if max_chunk_size is not None and region_end - region_start > max_chunk_size:
            edit_start = np.random.randint(region_start, region_end - max_chunk_size + 1)
            edit_end = edit_start + max_chunk_size
        else:
            edit_start, edit_end = region_start, region_end
        return self._expand_to_sentence_boundaries(text, edit_start, edit_end)

    @staticmethod
    def _expand_to_sentence_boundaries(
        text: str, start: int, end: int, max_expansion: int = 150
    ) -> Tuple[int, int]:
        """Expand the span [start:end] outward to the closest sentence boundaries, looking
        at most max_expansion characters beyond each end. If no sentence boundary is found
        within that distance, the span is only expanded to the closest word boundaries.

        Expanding outward (rather than shrinking inward) guarantees that the whole aligned
        region is covered by the edit, including the partial sentences at its edges which
        would otherwise keep aligning with the original text."""

        # Start: nothing to do if we are already right after a sentence boundary
        if start > 0 and not re.search(r"[.!?]\s*$", text[max(0, start - 2) : start]):
            left_limit = max(0, start - max_expansion)
            boundaries = list(re.finditer(r"[.!?]\s+", text[left_limit:start]))
            if boundaries:
                start = left_limit + boundaries[-1].end()
            else:
                last_space = text.rfind(" ", left_limit, start)
                if last_space != -1:
                    start = last_space + 1

        # End: nothing to do if we are already right after a sentence boundary
        if end < len(text) and not re.search(r"[.!?]\s*$", text[max(0, end - 2) : end]):
            right_limit = min(len(text), end + max_expansion)
            m = re.search(r"[.!?]", text[end:right_limit])
            if m:
                end = end + m.end()
            else:
                next_space = text.find(" ", end, right_limit)
                if next_space != -1:
                    end = next_space

        return (start, end)

    @staticmethod
    def _merge_windows(
        windows: List[Tuple[int, int, str]],
    ) -> List[Tuple[int, int, str]]:
        """Sort the (start, end, operation) windows by position and merge the ones that
        overlap or touch. A merged window is permuted if any of its parts was to be
        permuted (permuting a larger window still breaks the alignment), and paraphrased
        otherwise."""
        merged: List[Tuple[int, int, str]] = []
        for start, end, operation in sorted(windows):
            if merged and start <= merged[-1][1]:
                prev_start, prev_end, prev_operation = merged[-1]
                merged[-1] = (
                    prev_start,
                    max(prev_end, end),
                    "permute" if "permute" in (prev_operation, operation) else operation,
                )
            else:
                merged.append((start, end, operation))
        return merged

    def get_paraphrase(self, chunk: str, style: str = "conservative") -> str:
        """Use the LLM to generate a paraphrase of a single chunk of text (see
        get_paraphrases)."""
        return self.get_paraphrases([chunk], style=style)[0]

    def get_paraphrases(
        self,
        chunks: List[str],
        temperature: float = 0.8,
        style: str = "conservative",
    ) -> List[str]:
        """Use the LLM to generate paraphrases of the input chunks of text in a single
        batch. With the "conservative" style, the model is asked to keep most of the
        original words and only restructure the sentences; with the "aggressive" style,
        it is asked to change most of the words. Chunks whose paraphrase is implausibly
        short or long are returned unchanged."""

        if not chunks:
            return []
        if self.model is None:
            raise RuntimeError("LLM model not initialized for paraphrasing.")
        if style not in PROMPT_TEMPLATES:
            raise ValueError(
                f"Unknown paraphrase style {style!r}, expected one of {sorted(PROMPT_TEMPLATES)}"
            )
        prompt_template = PROMPT_TEMPLATES[style]

        # We set the sampling parameters
        import vllm

        sampling_params = vllm.SamplingParams(
            temperature=temperature, top_p=0.8, top_k=50, max_tokens=600, n=1
        )

        # We add the chunks to the prompt, one conversation per chunk
        conversations = [
            [{"role": "user", "content": prompt_template.format(text=chunk)}]
            for chunk in chunks
        ]

        # We call the model (outputs are returned in the same order as the inputs)
        outputs = self.model.chat(
            conversations,
            sampling_params,
            chat_template_kwargs={"enable_thinking": False},
        )

        # We extract the model's responses.
        paraphrases = []
        for chunk, output in zip(chunks, outputs):
            response = output.outputs[0].text.strip()
            if len(response) < len(chunk) * 0.3:
                print("WARNING: Paraphrased text is too short. Using original chunk.")
                paraphrases.append(chunk)
            elif len(response) > len(chunk) * 2.5:
                print("WARNING: Paraphrased text is too long. Using original chunk.")
                print("ORIGINAL:", chunk)
                print("PARAPHRASED:", response)
                paraphrases.append(chunk)
            else:
                paraphrases.append(response)

        return paraphrases

    def permute_chunks(
        self,
        text: str,
        target_chunk_size: Optional[float] = None,
        max_chunks: Optional[int] = None,
        reference: Optional[str] = None,
        nb_candidates: int = 3,
    ) -> str:
        """Randomly permute the order of a few chunks of the input text so that it no
        longer aligns with the reference text (the original document; by default the
        input text itself, when it has not been edited yet).

        Without target_chunk_size, the text is split into 2 to 8 chunks of random
        (Dirichlet-distributed) sizes. With target_chunk_size, it is split into chunks of
        about that size (as many as needed, whatever the length of the text, optionally
        bounded by max_chunks), all of them of nearly equal size: a region longer than
        the oracle threshold is thus cut into pieces below it, and no short chunk is
        produced, since a short chunk inserted between two originally adjacent chunks
        does not break their alignment (the aligner bridges it as a cheap gap) while
        its boundaries still destroy word n-grams.

        The chunks are then located in the reference and reordered by *decreasing*
        position in it, in shuffled blocks (see _descending_block_order). Up to
        nb_candidates such orders are drawn: the first one whose largest region aligned
        with the reference falls below self.min_oracle_score is kept, otherwise the one
        with the lowest score.
        """
        if target_chunk_size is None:
            nb_chunks = np.random.randint(2, 9)
            chunk_proportions = np.random.dirichlet(np.ones(nb_chunks), size=1)[0]
        else:
            nb_chunks = max(2, int(np.ceil(len(text) / target_chunk_size)))
            if max_chunks is not None:
                nb_chunks = min(nb_chunks, max_chunks)
            chunk_proportions = np.full(nb_chunks, 1.0 / nb_chunks)
        chunks = chunk_proportion(text, chunk_proportions=chunk_proportions)

        # If the text could not be split into at least two chunks (e.g. a single word),
        # a permutation cannot change anything, so we return the text as is.
        if len(chunks) < 2:
            print("WARNING: Could not split text into at least two chunks for permutation.")
            return text

        print(
            "Permuting %i chunks of sizes: %s"
            % (len(chunks), [len(c) for c in chunks])
        )
        if reference is None:
            reference = text
            positions = np.arange(len(chunks), dtype=float)
        else:
            positions = self._locate_chunks(reference, chunks)

        best_text, best_score = text, float("inf")
        for _ in range(max(1, nb_candidates)):
            order = self._descending_block_order(positions)
            candidate = " ".join(chunks[i] for i in order)
            score = self.aligner.get_largest_region_score(reference, candidate)
            if score < best_score:
                best_text, best_score = candidate, score
            if score < self.min_oracle_score:
                break
        return best_text

    def _locate_chunks(self, reference: str, chunks: List[str]) -> np.ndarray:
        """Return the position in the reference text of each chunk (the start of the
        region of the reference it aligns best with). Chunks which do not align with at
        least half of their length (e.g. paraphrased ones) get a random position."""
        positions = np.random.uniform(0, len(reference), len(chunks))
        for i, chunk in enumerate(chunks):
            regions = self.aligner.run(reference, chunk).regions
            if regions:
                best = max(regions, key=lambda r: r["score"])
                if best["score"] >= 0.5 * len(chunk):
                    positions[i] = best["start1"]
        return positions

    @staticmethod
    def _descending_block_order(positions: np.ndarray, max_blocks: int = 8) -> List[int]:
        """Draw a random order of the chunks in which their positions in the reference
        text are only ever locally *decreasing*: the chunks sorted by decreasing position
        are grouped into a random number of blocks (at most max_blocks), which are then
        shuffled.

        The oracle (Smith-Waterman) can only chain chunks that appear in increasing
        order in both texts, and substituting a chunk by an unrelated one of the same
        length is much cheaper than its length (shared characters, spaces...), so a plain
        random permutation typically leaves chains of two or three chunks in increasing
        order, close enough to be bridged, which keeps the region above the threshold.
        With descending blocks, a chain can use at most one chunk per block, and two
        originally adjacent chunks never stay adjacent in the same order.
        """
        descending = np.argsort(-positions, kind="stable")
        nb_chunks = len(descending)
        nb_blocks = np.random.randint(1, max(1, min(nb_chunks // 3, max_blocks)) + 1)
        cuts = np.sort(np.random.choice(np.arange(1, nb_chunks), nb_blocks - 1, replace=False))
        blocks = np.split(descending, cuts)
        return [int(i) for b in np.random.permutation(len(blocks)) for i in blocks[b]]


# Boundary patterns used to split a text into units, from strongest to weakest: sentence
# boundaries, then "soft" boundaries (clause punctuation, table cell separators, newlines),
# then plain whitespace. Weaker patterns are only used when the stronger ones do not yield
# enough units (e.g. for flattened tables, formulas or reference lists without sentences).
_UNIT_BOUNDARIES = [
    r"(?<=[.!?]) +",
    r"(?<=[.!?,;:|]) +|\s*\n\s*",
    r"\s+",
]


def split_units(
    text: str, min_units: int = 2, max_unit_size: Optional[int] = None
) -> List[str]:
    """Split the input text into non-empty units, preferably at sentence boundaries.

    If the sentence-level split yields fewer than min_units units, or if some units are
    longer than max_unit_size (when specified), those units are further split using
    progressively weaker boundaries (clause punctuation, cell separators, whitespace).
    Units that already satisfy the constraints are left untouched, so regular prose keeps
    its sentence-level granularity.
    """
    units = [text] if text else []
    for pattern in _UNIT_BOUNDARIES:
        too_few = len(units) < min_units
        new_units = []
        for unit in units:
            oversized = max_unit_size is not None and len(unit) > max_unit_size
            if too_few or oversized:
                new_units.extend(u for u in re.split(pattern, unit) if u)
            else:
                new_units.append(unit)
        units = new_units
        if len(units) >= min_units and (
            max_unit_size is None or all(len(u) <= max_unit_size for u in units)
        ):
            break
    return units


def chunk_min(text, min_chunk_size=400):
    """Split the input text into chunks of a specified size, ensuring that splits occur
    at sentence boundaries when possible.

    Each chunk should be at least min_chunk_size characters long.
    """
    if min_chunk_size >= len(text):
        raise ValueError(
            "min_chunk_size must be smaller than the length of the input text."
        )

    # Units much longer than the chunk size (typically sentence-free blocks such as tables)
    # are sub-split at weaker boundaries; ordinary long sentences are left intact.
    sentences = split_units(text, max_unit_size=3 * min_chunk_size)
    chunks = []
    current_chunk = ""
    for sentence in sentences:
        current_chunk += " " + sentence if current_chunk else sentence
        if len(current_chunk) > min_chunk_size:
            chunks.append(current_chunk.strip())
            current_chunk = ""

    if current_chunk:
        if chunks:
            chunks[-1] += " " + current_chunk.strip()
        else:
            print("WARNING: single chunk of size", len(current_chunk))
            chunks.append(current_chunk.strip())

    return chunks


def chunk_max(text, max_chunk_size=400):
    """Split the input text into chunks of a specified size, ensuring that splits occur
    at sentence boundaries when possible.

    Each chunk should be at most max_chunk_size characters long.
    """
    sentences = split_units(text, max_unit_size=max_chunk_size)
    chunks = []
    current_chunk = ""
    for sentence in sentences:
        new_chunk = current_chunk + " " + sentence if current_chunk else sentence
        if current_chunk and len(new_chunk) > max_chunk_size:
            chunks.append(current_chunk.strip())
            current_chunk = sentence
        else:
            current_chunk = new_chunk

    if current_chunk:
        chunks.append(current_chunk.strip())

    return chunks


def chunk_proportion(text, chunk_proportions: List[float]):
    """Split the input text into chunks, where the approximate size of each chunk is
    determined by the corresponding value in chunk_proportions. The method ensures that
    splits occur at sentence boundaries when possible.

    Args:
        text: The input text to be chunked.
        chunk_proportions: A list of relative sizes for each chunk. The values should sum to 1.

    Returns:
        A list of text chunks corresponding to the specified relative sizes.

    """
    if not np.isclose(sum(chunk_proportions), 1.0, atol=1e-2):
        raise ValueError("The values in chunk_proportions should sum to 1.")

    units = split_units(text, min_units=len(chunk_proportions))
    total_length = len(text)

    # Cut points (in characters) between consecutive chunks; each unit is assigned to
    # the chunk whose cut point lies beyond the unit's midpoint.
    cut_points = np.cumsum(chunk_proportions) * total_length
    chunks: List[str] = [""] * len(chunk_proportions)
    position = 0
    for unit in units:
        midpoint = position + len(unit) / 2
        chunk_idx = min(int(np.searchsorted(cut_points, midpoint)), len(chunks) - 1)
        chunks[chunk_idx] = (chunks[chunk_idx] + " " + unit) if chunks[chunk_idx] else unit
        position += len(unit) + 1

    return [c.strip() for c in chunks if c.strip()]


def word_ngram_overlap(source_text: str, edited_text: str, n: int = 5) -> float:
    """Fraction of the word n-grams of the edited text which also occur in the source
    text (0 if the edited text has fewer than n words). This is a cheap diagnostic of
    how much of the original wording a negative example retains, independently of the
    oracle alignment score."""
    source_words = source_text.split()
    edited_words = edited_text.split()
    if len(edited_words) < n:
        return 0.0
    source_ngrams = {
        tuple(source_words[i : i + n]) for i in range(len(source_words) - n + 1)
    }
    edited_ngrams = [
        tuple(edited_words[i : i + n]) for i in range(len(edited_words) - n + 1)
    ]
    return sum(1 for ng in edited_ngrams if ng in source_ngrams) / len(edited_ngrams)


def word_edit_rate(source_text: str, edited_text: str) -> float:
    """Fraction of the words of the source text that do not survive unchanged, in
    order, in the edited text (0 for identical texts, 1 if nothing is kept).

    Words are whitespace-delimited and compared exactly, so a case flip, a hyphen or a
    ligature counts as one changed word, as it does for exact word-matching methods;
    inserted words (e.g. boilerplate) do not count as changes.  This bounds the share
    of word n-grams a positive can lose independently of the oracle alignment score,
    which is lenient with such edits.
    """
    source_words = source_text.split()
    if not source_words:
        return 0.0
    matcher = difflib.SequenceMatcher(
        None, source_words, edited_text.split(), autojunk=False
    )
    kept = sum(block.size for block in matcher.get_matching_blocks())
    return 1.0 - kept / len(source_words)


# ===================================================================== pipeline
#
# Building a benchmark goes through four steps, each writing one JSONL file:
#
#   sample_corpus       corpus file(s) ---------------> corpus_sample.jsonl
#   generate_negatives  corpus_sample ----------------> negatives.jsonl
#   generate_positives  corpus_sample + out-of-corpus -> positives.jsonl
#   merge_examples      positives + negatives --------> benchmark.jsonl
#
# build_benchmark chains them.  The generation steps append to their output file
# under a file lock and stop once it holds nb_examples lines, so that several jobs
# can fill the same file concurrently and an interrupted run can simply be restarted.

POSITIVE = "positive"
NEGATIVE = "negative"

CORPUS_SUFFIXES = (".jsonl", ".jsonl.gz", ".jsonl.zst")

# Fields of the generated examples that are only useful for debugging and are
# dropped from the merged benchmark unless requested
BULKY_FIELDS = ("source_text", "before", "after")


def _list_corpus_files(corpus: Union[str, Iterable[str]]) -> List[str]:
    """Resolve a corpus specification (a corpus file, a directory of corpus files, or
    a collection of files and directories) to a sorted list of corpus files."""
    if isinstance(corpus, str):
        corpus = [corpus]
    files: List[str] = []
    for entry in corpus:
        if os.path.isdir(entry):
            found = utils.get_filtered_files(entry, file_suffixes=CORPUS_SUFFIXES)
            if not found:
                raise ValueError(f"No {'/'.join(CORPUS_SUFFIXES)} files in {entry}")
            files.extend(found)
        elif os.path.isfile(entry):
            if not entry.endswith(CORPUS_SUFFIXES):
                raise ValueError(f"Unsupported corpus file format: {entry}")
            files.append(entry)
        else:
            raise FileNotFoundError(entry)
    return sorted(dict.fromkeys(files))


def _stream_corpus_file(corpus_file: str, **kwargs) -> Iterable[dict]:
    if corpus_file.endswith(".zst"):
        return utils.stream_json_zst(corpus_file, **kwargs)
    return utils.stream_jsonl(corpus_file, **kwargs)


def count_lines(path: str) -> int:
    """Number of non-empty lines of a file (0 if it does not exist)."""
    if not os.path.exists(path):
        return 0
    with open(path, "rb") as f:
        return sum(1 for line in f if line.strip())


def median_text_length(jsonl_path: str) -> int:
    """Median length (in characters) of the ``text`` field of the examples of a JSONL
    file, typically used to pad the positives to the length of the negatives."""
    lengths = []
    with open(jsonl_path, "rb") as f:
        for line in f:
            if line.strip():
                lengths.append(len(orjson.loads(line)["text"]))
    if not lengths:
        raise ValueError(f"{jsonl_path} is empty")
    return int(np.median(lengths))


def _append_until(
    output_path: str,
    nb_examples: Optional[int],
    make_example: Callable[[], Optional[dict]],
    overwrite: bool = False,
) -> str:
    """Call make_example repeatedly and append its results to output_path (one JSON
    object per line) until the file holds at least nb_examples lines.

    The file may already contain examples (from a previous or a concurrent job): the
    line count is taken under a file lock after every write, so several processes can
    safely fill the same file.  With nb_examples=None, the loop runs until the process
    is killed.  Examples returned as None are skipped, and exceptions raised by
    make_example are logged and skipped so that a single pathological document does not
    bring down a long job.  Returns output_path.
    """
    if overwrite and os.path.exists(output_path):
        os.remove(output_path)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    lock = filelock.FileLock(f"{output_path}.lock")

    with lock:
        nb_done = count_lines(output_path)
    if nb_examples is not None and nb_done >= nb_examples:
        print(f"{output_path} already holds {nb_done} examples, nothing to do")
        return output_path

    print(f"Appending examples to {output_path} ({nb_done} present)", flush=True)
    while True:
        try:
            example = make_example()
        except Exception as e:
            print(f"Error while generating example, skipping: {e}", flush=True)
            continue
        if example is None:
            continue
        with lock:
            with open(output_path, "ab") as f:
                f.write(orjson.dumps(example))
                f.write(b"\n")
            nb_done = count_lines(output_path)
        print(f"DONE ({nb_done} examples in {output_path})", flush=True)
        if nb_examples is not None and nb_done >= nb_examples:
            print(f"Reached {nb_examples} examples in {output_path}")
            return output_path


def sample_corpus(
    corpus: Union[str, Iterable[str]],
    nb_docs: int,
    output_path: str,
    skip_prob: float = 0.9,
    min_length: int = 1_200,
    max_length: int = 15_000,
) -> str:
    """Step 1: write nb_docs documents of a corpus to output_path (JSONL, one document
    per line, with normalised ``id`` and ``text`` fields).

    The corpus files are too large for true random sampling, so each file is read from
    the start with a high skip probability and left as soon as its share (nb_docs split
    evenly over the files) has been collected.  The sample is thus drawn from roughly
    the first share/(1-skip_prob) documents of every file.

    Args:
        corpus: a corpus file (.jsonl, .jsonl.gz or .jsonl.zst), a directory of such
            files, or a collection of files and directories.
        nb_docs: number of documents to sample.
        output_path: destination JSONL file (overwritten).
        skip_prob: probability of skipping a document while reading the corpus.
        min_length, max_length: length bounds (in characters) of the sampled documents.

    Returns: output_path.
    """
    if nb_docs <= 0:
        raise ValueError("nb_docs must be positive")
    if not 0.0 <= skip_prob < 1.0:
        raise ValueError("skip_prob must be in [0, 1)")
    corpus_files = _list_corpus_files(corpus)

    # Spread the quota evenly, giving the remainder to the first files
    base, extra = divmod(nb_docs, len(corpus_files))
    quotas = [base + (1 if i < extra else 0) for i in range(len(corpus_files))]
    for corpus_file, quota in zip(corpus_files, quotas):
        print(f"Sampling {quota:,} documents from {corpus_file}", flush=True)

    count = 0
    progress_bar = tqdm.tqdm(total=nb_docs, desc="Sampling documents", unit="doc")
    with open(output_path, "w", encoding="utf-8") as f:
        for corpus_file, quota in zip(corpus_files, quotas):
            if quota == 0:
                break  # quotas are non-increasing, so the remaining ones are 0 too
            stream = _stream_corpus_file(
                corpus_file,
                skip_prob=skip_prob,
                min_length=min_length,
                max_length=max_length,
                max_nb=quota,
            )
            for doc in stream:
                f.write(orjson.dumps(doc).decode("utf-8"))
                f.write("\n")
                count += 1
                progress_bar.update(1)
    progress_bar.close()
    if count < nb_docs:
        print(
            f"WARNING: only {count:,} of the requested {nb_docs:,} documents could be "
            "sampled (corpus too small for the length bounds and skip probability)"
        )
    print(f"Wrote {count:,} documents to {output_path}")
    return output_path


def generate_negatives(
    corpus_sample: str,
    output_path: str,
    nb_examples: Optional[int] = 1000,
    sw_threshold: float = 100,
    use_llm: bool = True,
    paraphrase_fraction: float = 0.5,
    overwrite: bool = False,
) -> str:
    """Step 2: generate negative examples from the documents of corpus_sample and
    append them to output_path until it holds nb_examples lines.

    Each negative is a document of the sample edited (permutations and, with an LLM,
    conservative paraphrases, see NegativeExampleGenerator) until its largest
    Smith-Waterman alignment with the original falls below sw_threshold.  The negatives
    are thus "hard": they keep most of the original wording.

    Args:
        corpus_sample: JSONL file of corpus documents (see sample_corpus).
        output_path: destination JSONL file, appended to (see _append_until).
        nb_examples: number of lines output_path should hold at the end (None: run
            until killed).
        sw_threshold: Smith-Waterman score the negatives must stay below.
        use_llm: use an LLM for paraphrasing, or only rely on permutations.
        paraphrase_fraction: fraction of the chunks of each document paraphrased after
            the global permutation (controls how much original wording is kept).
        overwrite: delete output_path first instead of appending to it.

    Each line has the fields ``text``, ``type`` ("negative"), ``source_doc_id``,
    ``source_text``, ``oracle_score``, ``ngram_overlap``, ``nb_steps``,
    ``nb_permutations`` and ``nb_paraphrases``.  Returns output_path.
    """
    if nb_examples is not None and not overwrite and count_lines(output_path) >= nb_examples:
        print(f"{output_path} already holds {nb_examples} examples, nothing to do")
        return output_path

    generator = NegativeExampleGenerator(
        Corpus(corpus_sample),
        llm_model="Qwen/Qwen2-7B-Instruct" if use_llm else None,
        min_oracle_score=sw_threshold,
        paraphrase_fraction=paraphrase_fraction,
    )

    def make_example() -> dict:
        print("Start sampling negative example pair", flush=True)
        ex = generator.sample_negative()
        return {
            "text": ex["text2"],
            "type": NEGATIVE,
            "source_doc_id": ex["meta"]["id"],
            "source_text": ex["text1"],
            "oracle_score": ex["score"],
            "ngram_overlap": ex["ngram_overlap"],
            "nb_steps": ex["nb_steps"],
            "nb_permutations": ex["operations"].get("permute", 0),
            "nb_paraphrases": sum(
                n for op, n in ex["operations"].items() if op != "permute"
            ),
        }

    return _append_until(output_path, nb_examples, make_example, overwrite)


def generate_positives(
    corpus_sample: str,
    out_of_corpus_sample: str,
    output_path: str,
    nb_examples: Optional[int] = 1000,
    sw_threshold: float = 1000,
    target_length: Union[int, str, None] = None,
    overwrite: bool = False,
    max_fragment_share: Optional[float] = 0.5,
    max_score_loss: Optional[float] = None,
    max_word_edit_rate: float = 0.1,
) -> str:
    """Step 3: generate positive examples from the documents of corpus_sample and
    append them to output_path until it holds nb_examples lines.

    Each positive is a chunk of a document of the sample, perturbed (hyphenation,
    casing, boilerplate, unicode normalisation, see PositiveExampleGenerator) while
    still sharing a segment of Smith-Waterman score at least sw_threshold with the
    original, then padded with texts of out_of_corpus_sample up to target_length.

    Args:
        corpus_sample: JSONL file of corpus documents (see sample_corpus).
        out_of_corpus_sample: JSONL file of documents that are *not* in the indexed
            corpus, used for padding.
        output_path: destination JSONL file, appended to (see _append_until).
        nb_examples: number of lines output_path should hold at the end (None: run
            until killed).
        sw_threshold: minimum Smith-Waterman score of the shared segment.
        target_length: length (in characters) the positives are padded to.  An int is
            used as is; a path to a JSONL file of examples (typically the negatives)
            means "the median text length of that file", so that the positives have the
            same length as the negatives; None disables padding.
        overwrite: delete output_path first instead of appending to it.
        max_fragment_share: the length of the shared fragment is drawn uniformly between
            sw_threshold and this share of target_length (default 0.5: the fragment
            makes up to half of the query).  None, or no target_length, gives
            fragments of about sw_threshold characters only (the hardest positives).
        max_score_loss: see PositiveExampleGenerator (default: 5 % of sw_threshold).
        max_word_edit_rate: largest fraction of the words of the fragment the edits may
            change (see PositiveExampleGenerator; default 0.1).

    Each line has the fields ``text``, ``type`` ("positive"), ``source_doc_id``,
    ``source_text``, ``oracle_score``, ``fragment_length``, ``word_edit_rate`` and the
    padding texts in ``before`` / ``after``.  Returns output_path.
    """
    if nb_examples is not None and not overwrite and count_lines(output_path) >= nb_examples:
        print(f"{output_path} already holds {nb_examples} examples, nothing to do")
        return output_path

    if isinstance(target_length, str):
        target_length = median_text_length(target_length)
        print(f"Target length of the positives (median of the negatives): {target_length}")
    elif target_length is None:
        target_length = 0

    max_fragment_length = None
    if max_fragment_share is not None and target_length > 0:
        max_fragment_length = max(int(max_fragment_share * target_length), int(sw_threshold))
        print(f"Fragment length of the positives: {sw_threshold:g} to {max_fragment_length}")

    generator = PositiveExampleGenerator(
        corpus=Corpus(corpus_sample),
        other_corpus=Corpus(out_of_corpus_sample),
        min_oracle_score=sw_threshold,
        target_text_length=target_length,
        max_fragment_length=max_fragment_length,
        max_score_loss=max_score_loss,
        max_word_edit_rate=max_word_edit_rate,
    )

    def make_example() -> Optional[dict]:
        ex = generator.sample_positive()
        if ex is None:
            return None
        result = {
            "text": ex["text2"],
            "type": POSITIVE,
            "source_doc_id": ex["meta"]["id"],
            "source_text": ex["text1"],
            "oracle_score": ex["score"],
            "fragment_length": ex.get("fragment_length"),
            "word_edit_rate": ex.get("word_edit_rate"),
        }
        for side in ("before", "after"):
            if side in ex:
                result[side] = ex[side]
        return result

    return _append_until(output_path, nb_examples, make_example, overwrite)


def merge_examples(
    positives_path: str,
    negatives_path: str,
    output_path: str,
    nb_examples: int,
    seed: Optional[int] = None,
    keep_source_texts: bool = False,
) -> str:
    """Step 4: write a shuffled benchmark of nb_examples examples, half positives and
    half negatives, drawn from the two JSONL files.

    The examples are drawn without replacement (with replacement, and a warning, when
    a file is too short).  Their ``type`` is set from the file they come from, and the
    bulky debugging fields (source_text, before, after) are dropped unless
    keep_source_texts is True.

    Args:
        positives_path: JSONL file of positive examples (see generate_positives).
        negatives_path: JSONL file of negative examples (see generate_negatives).
        output_path: destination JSONL file of the benchmark.
        nb_examples: total number of examples; with an odd number, the extra example
            is a positive.
        seed: optional random seed for reproducibility.
        keep_source_texts: whether to keep the bulky debugging fields.

    Returns: output_path.
    """
    nb_neg = nb_examples // 2
    nb_pos = nb_examples - nb_neg
    rng = random.Random(seed)
    examples = _draw_examples(positives_path, nb_pos, POSITIVE, rng, keep_source_texts)
    examples += _draw_examples(negatives_path, nb_neg, NEGATIVE, rng, keep_source_texts)
    rng.shuffle(examples)
    with open(output_path, "wb") as f:
        for ex in examples:
            f.write(orjson.dumps(ex))
            f.write(b"\n")
    print(f"Wrote {nb_pos} positives and {nb_neg} negatives to {output_path}")
    return output_path


def _draw_examples(
    path: str, n: int, label: str, rng: random.Random, keep_source_texts: bool
) -> List[dict]:
    with open(path, "rb") as f:
        lines = [line for line in f if line.strip()]
    if not lines:
        raise ValueError(f"{path} is empty")
    if n > len(lines):
        print(
            f"{path} has only {len(lines)} examples but {n} requested: "
            "resampling with replacement"
        )
        lines = [rng.choice(lines) for _ in range(n)]
    else:
        lines = rng.sample(lines, n)
    examples = []
    for line in lines:
        ex = orjson.loads(line)
        if not keep_source_texts:
            ex = {k: v for k, v in ex.items() if k not in BULKY_FIELDS}
        ex["type"] = label
        if label == POSITIVE and ex.get("source_doc_id") is None:
            raise ValueError(f"positive example in {path} lacks a 'source_doc_id'")
        examples.append(ex)
    return examples

