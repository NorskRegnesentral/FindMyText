class Corpus:
    """Corpus of documents which can be sampled."""

    def __init__(self, jsonl_path: Optional[str] = None):
        """Initialize the Corpus by loading documents from a JSONL file."""
        self.data = []
        if jsonl_path is not None:
            with open(jsonl_path, "r") as f:
                for line in f:
                    self.data.append(orjson.loads(line))

    def sample_doc(self, min_length: int = 1000, max_length: int = 50000):
        """Sample a document from the corpus that meets the minimum length
        requirement."""
        MAX_ATTEMPTS = 1000
        attempts = 0
        while attempts < MAX_ATTEMPTS:
            doc = np.random.choice(self.data)
            doc_text = doc["text"]
            if len(doc_text) >= min_length and len(doc_text) <= max_length:
                basic_doc = {
                    k: v
                    for k, v in doc.items()
                    if k not in {"seg_langs", "web-register", "doc_scores"}
                }
                return basic_doc
            attempts += 1
        raise RuntimeError(
            f"Could not find a document of at least {min_length} characters and at most {max_length} characters after {MAX_ATTEMPTS} attempts."
        )


class PositiveExampleGenerator:
    """Generator for positive example pairs (that is, pairs of texts which do contains a
    shared segment according to the oracle) from a corpus."""

    def __init__(
        self,
        corpus: Corpus,
        other_corpus: Optional[Corpus] = None,
        min_oracle_score: float = 1000,
        target_text_length: int = 2000,
    ):
        """Initialize the PositiveExampleGenerator with a hyphenation dictionary and an
        oracle."""
        self.corpus = corpus
        if other_corpus is not None:
            self.other_corpus = other_corpus
        else:
            self.other_corpus = corpus
        self.dic = pyphen.Pyphen(lang="en")
        self.local_aligner = oracle.LocalAligner()
        self.min_oracle_score = min_oracle_score
        self.target_text_length = target_text_length

    def sample_positive(self) -> Optional[dict]:
        """Sample a positive example pair from the corpus.

        The method first samples a document from the corpus, then selects a random chunk
        of text from that document to edit. It applies a series of random edits to the
        selected chunk, while ensuring that the edited text remains sufficiently similar
        to the original text according to an oracle function. In case the edited text is
        shorter than the target length, the method expands it by concatenating random
        samples of text from the corpus.

        Returns: A dictionary containing the original text, the edited text, their pair
        type (positive), and metadata about the source document and any documents used
        for expansion.
        """
        doc = self.corpus.sample_doc(int(self.min_oracle_score * 1.1), 50000)
        doc_text = doc["text"]

        # We select a random chunk of text from the document to edit, with a minimum
        # length equal to the minimum oracle score to ensure that we have enough room
        # for edits while still retaining a shared segment that is sufficiently long.
        min_chunk_size = int(self.min_oracle_score)
        chunks = chunk_min(doc_text, min_chunk_size=min_chunk_size)
        suitable_chunks = [
            c
            for c in chunks
            if len(c) < self.min_oracle_score * 1.05 and len(c) >= min_chunk_size + 10
        ]
        if not suitable_chunks:
            print("No suitable chunks found. Skipping.")
            return None
        chunk_to_edit = np.random.choice(suitable_chunks)

        doc_id = doc.get("u", doc.get("id", "unknown"))
        print(
            "Working on chunk from %s of length %i" % (doc_id, len(chunk_to_edit)),
            flush=True,
        )

        edited_text, region_score = self.edit_text(chunk_to_edit)
        if region_score < self.min_oracle_score:
            print("\nCould not edit text:", chunk_to_edit)
            print("Final score:", region_score)
            return

        meta_data = {k: v for k, v in doc.items() if k not in {"text"}}

        # If the edited text is shorter than the target length, we expand it by concatenating random
        # samples of text from the corpus before and after it, until the target length is reached.
        edited_text, expansion_meta = self.expand_to_target_length(edited_text)

        result = {
            "text1": doc_text,
            "text2": edited_text,
            "pair_type": "positive",
            "score": region_score,
            "meta": meta_data,
            **expansion_meta,
        }
        return result

    def expand_to_target_length(self, text: str) -> Tuple[str, Dict[str, Any]]:
        """If the input text is shorter than the target length, expand it by
        concatenating random samples of text from the corpus before and after it, until
        the target length is reached.

        The method also returns metadata about the documents used for expansion.
        """
        meta_data = {"before": []}
        expanded_text = text

        # If the text is shorter than the target length, we add a preamble text from another document.
        while len(expanded_text) < self.target_text_length:
            nb_to_add = self.target_text_length - len(expanded_text)
            preamble_doc = self.other_corpus.sample_doc()
            preamble_text = preamble_doc["text"]
            if len(preamble_text) > nb_to_add:
                preamble_text = chunk_min(preamble_text, min_chunk_size=nb_to_add)[0]
            expanded_text = preamble_text + " " + expanded_text
            meta_data["before"].append(
                {"doc_id": preamble_doc["id"], "added": preamble_text}
            )
            print("Added preamble text of length %i" % len(preamble_text))

        return expanded_text, meta_data

    def edit_text(self, text, nb_attempts=500, timeout=300) -> Tuple[str, float]:
        """Apply a series of random edits to the input text, while ensuring that the
        edited text remains sufficiently similar to the original text according to an
        oracle function.

        The edits include adding hyphenation, changing casing, adding boilerplate
        segments, and switching normalisation of unicode characters. The function
        returns the final edited text after applying a series of edits that are accepted
        by the oracle.

        Args:
            text: The input text to edit.
            nb_attempts: The maximum number of edit attempts to apply to the text.
            timeout: The maximum time in seconds to spend on editing the text.

        Returns:
            A tuple containing the final edited text and its oracle score compared to the original text.

        """

        initial_text = str(text)
        successive_edits = []

        init_time = time.time()
        for _ in range(nb_attempts):
            if time.time() - init_time > timeout:
                break
            edit_functions = [
                self.add_hyphenation,
                self.change_casing,
                self.add_boilerplate_segment,
                self.switch_normalisation,
            ]
            chosen_edit_function = edit_functions[
                np.random.randint(len(edit_functions))
            ]
            edited_text = chosen_edit_function(text)
            if edited_text == text:
                continue

            print(".", end="", flush=True)
            region_score = self.local_aligner.get_largest_region_score(
                initial_text, edited_text
            )

            if region_score < self.min_oracle_score:
                if len(successive_edits) > 0:
                    print("OK", flush=True)
                    return successive_edits[-1]
                else:
                    continue

            successive_edits.append((edited_text, region_score))
            text = edited_text

        print("KO", flush=True)
        return initial_text, 0.0

    def add_hyphenation(self, text, nb_to_hyphenate=2) -> str:
        """Hyphenates a few words based on actual linguistic syllable boundaries."""
        words = text.split()

        # Shuffle words to avoid always picking the first eligible word
        indices = np.arange(len(words))
        np.random.shuffle(indices)

        hyphenated_words = 0
        for idx in indices:
            word = words[idx]

            # Strip punctuation for cleaner processing
            clean_word = word.strip('.,!?;:()"')
            if len(clean_word) < 5:  # Short words rarely wrap
                continue

            # Get hyphenation positions (e.g., 'hyphenation' -> 'hy-phen-ation')
            hyphenated_style = self.dic.inserted(clean_word)

            if "-" in hyphenated_style:
                # Choose a random hyphenation point provided by the dictionary
                parts = hyphenated_style.split("-")
                split_idx = np.random.randint(1, len(parts))

                head = "".join(parts[:split_idx])
                tail = "".join(parts[split_idx:])

                # Randomly decide whether to insert a newline after the hyphen to mimic line breaks in PDFs
                if random.random() > 0.5:
                    new_word = f"{head}-{tail}"
                else:
                    new_word = f"{head}-\n{tail}"

                # Replace only the specific instance of the word
                words[idx] = word.replace(clean_word, new_word)
                hyphenated_words += 1

                if hyphenated_words >= nb_to_hyphenate:
                    return " ".join(words)

        return text  # Return original if no suitable word found

    def change_casing(self, text, nb_to_change=3) -> str:
        """Randomly changes the casing of a few words in the text."""
        words = text.split()

        nb_changed = 0
        while nb_changed < nb_to_change:
            # In 50% of cases, we change the casing of a titled word to lowercase
            if np.random.rand() < 0.5:
                titled_indices = [i for i, w in enumerate(words) if w.istitle()]
                if titled_indices:
                    idx = np.random.choice(titled_indices)
                    words[idx] = words[idx].lower()
                    nb_changed += 1
            # Otherwise, we change the casing of a lowercase word to either uppercase or title case
            else:
                lowercase_indices = [i for i, w in enumerate(words) if w.islower()]
                if lowercase_indices:
                    idx = np.random.choice(lowercase_indices)
                    if np.random.rand() < 0.5:
                        words[idx] = words[idx].upper()
                    else:
                        words[idx] = words[idx].title()
                    nb_changed += 1

        return " ".join(words)

    def add_boilerplate_segment(self, text) -> str:
        """Add a short boilerplate string at a random position in the text, to mimic
        text that could have been extracted from a PDF or a crawled web page."""
        segment = np.random.choice(BOILERPLATE_SEGMENTS)
        words = text.split()
        insert_idx = np.random.randint(0, len(words) + 1)
        words.insert(insert_idx, segment)
        return " ".join(words)

    def switch_normalisation(self, text) -> str:
        """Switch the normalisation of some unicode characters, such as changing
        straight quotes to curly quotes, or changing hyphens to en-dashes.

        Only reverse one type of character at a time.
        """
        transformations = [
            (r'"(.*?)"', r"“\1”"),  # Straight quotes to curly quotes
            (r"“(.*?)”", r'"\1"'),  # Curly quotes to straight quotes
            (r"'(.*?)'", r"‘\1’"),  # Straight single quotes to curly single quotes
            (r"‘(.*?)’", r"'\1'"),  # Curly single quotes to straight single quotes
            (r"'", r"’"),  # ASCII apostrophe to right single quotation mark
            (r"’", r"'"),  # Right single quotation mark to ASCII apostrophe
            (r"--", r"—"),  # Double hyphens to em-dash
            (r"—", r"--"),  # em-dash to double hyphens
            (r"-", r"–"),  # Hyphens to en-dash
            (r"–", r"-"),  # En-dash to hyphens
            (r"\.\.\.", r"…"),  # Three dots to ellipsis
            (r"…", r"..."),  # Ellipsis to three dots
            (r"fi", r"ﬁ"),  # fi ligature
            (r"ﬁ", r"fi"),  # fi ligature expanded
            (r"fl", r"ﬂ"),  # fl ligature
            (r"ﬂ", r"fl"),  # fl ligature expanded
            (r"\(c\)", "©"),  # Copyright symbol
            (r"©", "(c)"),  # Copyright symbol
            (r"\(r\)", "®"),  # Registered trademark symbol
            (r"®", "(r)"),  # Registered trademark symbol
            (r"\(tm\)", "™"),  # Trademark symbol
            (r"™", "(tm)"),  # Trademark symbol
        ]

        order = np.random.permutation(len(transformations))
        for idx in order:
            pattern, replacement = transformations[idx]
            matches = list(re.finditer(pattern, text))
            if not matches:
                continue

            match = matches[np.random.randint(len(matches))]
            replaced = re.sub(pattern, replacement, match.group(0), count=1)
            return text[: match.start()] + replaced + text[match.end() :]

        return text


class NegativeExampleGenerator:
    """Generator for negative example pairs (that is, pairs of texts which do not contain a
    shared segment according to the oracle) from a corpus."""

    def __init__(
        self,
        corpus: Corpus,
        llm_model: Optional[str] = "Qwen/Qwen2-7B-Instruct",
        min_oracle_score: float = 1000,
    ):
        """Initialize the NegativeExampleGenerator with a corpus and an LLM model."""
        self.corpus = corpus
        if llm_model is None:
            self.model = None
        else:
            import vllm

            # Whole documents are paraphrased in one batch of ~500-char chunks, so we let
            # vLLM process many sequences at once
            self.model = vllm.LLM(
                model=llm_model,
                max_num_batched_tokens=8192,
                max_model_len=3000,
                max_num_seqs=64,
                gpu_memory_utilization=0.80,
                tensor_parallel_size=1,
            )
        self.aligner = oracle.LocalAligner()
        self.min_oracle_score = min_oracle_score

    def sample_negative(
        self,
        max_nb_attempts=50,
        max_regions_per_step=16,
        global_permutation=True,
        debug=False,
    ) -> dict:
        """Sample a negative example from the corpus by randomly selecting a document
        and editing it so that it no longer shares any segment with the original
        according to the oracle function.

        The editing proceeds in three phases:
        1. (optional) a single global permutation of a few large chunks of the document,
           to also alter its overall structure;
        2. a paraphrase of the whole document by the LLM, done in a single batch of
           chunks of at most 500 characters;
        3. "mop-up" rounds, where all regions of the text that still align with the
           original above the threshold (up to max_regions_per_step) are paraphrased again
           at once, until the oracle score falls below the threshold.

        Each round of alignment with the original text is costly for long documents, so
        phases 1 and 2 only run one alignment each, and the number of mop-up rounds is
        typically small. If no LLM is available, the method falls back to repeated
        permutations.

        Returns: A dictionary containing the original text, the edited text, their pair
        type (negative), and metadata about the example.
        """

        # We sample a document from the corpus that is long enough to allow for editing
        # but not too long to avoid excessively long processing times.
        doc = self.corpus.sample_doc(int(self.min_oracle_score * 2.0), 30000)

        initial_text = str(doc["text"])
        initial_text_nobreaks = re.sub(r"\s+", " ", initial_text).strip()
        print("Working on text", doc["id"], flush=True)
        if debug:
            print("Original text:", initial_text_nobreaks)

        cur_score = len(initial_text_nobreaks)
        cur_text = str(initial_text_nobreaks)

        step_nr = 1

        # Phase 1: a single global permutation, to also alter the structure of the document
        if global_permutation:
            print("STEP %i:" % (step_nr), flush=True)
            print("Global permutation of the document")
            cur_text = self.permute_chunks(cur_text)
            cur_text = re.sub(r"\s+", " ", cur_text).strip()
            cur_score = self.aligner.get_largest_region_score(
                initial_text_nobreaks, cur_text
            )
            print("==> Region score after edit: %.1f" % cur_score)
            step_nr += 1

        # Phase 2: paraphrase of the whole document in one batch
        if self.model is not None and cur_score >= self.min_oracle_score:
            print("STEP %i:" % (step_nr), flush=True)
            chunks = chunk_max(cur_text, max_chunk_size=500)
            print("Paraphrasing the whole document (%i chunks)" % len(chunks))
            new_text = " ".join(self.get_paraphrases(chunks))
            new_text = re.sub(r"\s+", " ", new_text).strip()
            new_score = self.aligner.get_largest_region_score(
                initial_text_nobreaks, new_text
            )
            print("==> Region score after edit: %.1f" % new_score)
            if new_score <= cur_score:
                cur_text, cur_score = new_text, new_score
            else:
                print("WARNING: Region score increased after edit, skipping step")
            step_nr += 1

        # Phase 3: mop-up rounds on the regions that still align with the original
        nb_consecutive_skips = 0
        while step_nr <= max_nb_attempts and cur_score >= self.min_oracle_score:
            print("STEP %i:" % (step_nr), flush=True)

            # We identify all regions of the current text that still align with the
            # original text above the threshold, so that they can all be edited at once
            regions = self._find_regions_to_edit(
                initial_text_nobreaks,
                cur_text,
                min_score=self.min_oracle_score,
                max_regions=max_regions_per_step,
            )
            if not regions:
                break
            print(
                "Found %i region(s) above threshold, scores: %s"
                % (len(regions), [round(r[2]) for r in regions])
            )

            # If the last edits did not make any progress, the regions are probably
            # resistant to edits (e.g. a flattened table or a long URL/formula), so we
            # instead pick random sub-regions to break the deterministic choice of edit
            # windows, and sample the paraphrases at a higher temperature.
            stuck = nb_consecutive_skips >= 2
            windows = []
            for region_start, region_end, _ in regions:
                region_len = region_end - region_start
                if stuck and region_len > 60:
                    sub_region_size = np.random.randint(
                        max(30, region_len // 4), region_len
                    )
                    windows.append(
                        self._select_window(
                            cur_text, region_start, region_end, sub_region_size
                        )
                    )
                else:
                    windows.append(
                        self._select_window(cur_text, region_start, region_end)
                    )
            windows = self._merge_windows(windows)

            # Each window is paraphrased (in chunks of at most 500 characters, all sent to
            # the LLM in a single batch). Permutation is only used as a fallback when no
            # LLM is available: at this scale, permuting already-permuted fragments is a
            # random walk which re-joins fragments as often as it splits them.
            edits: List[Dict[str, Any]] = []
            paraphrase_chunks: List[str] = []
            for edit_start, edit_end in windows:
                chunk_to_edit = cur_text[edit_start:edit_end]
                edit = {"start": edit_start, "end": edit_end, "original": chunk_to_edit}
                if self.model is None:
                    print("Permutation of region [%i:%i]" % (edit_start, edit_end))
                    edit["edited"] = self.permute_chunks(chunk_to_edit)
                else:
                    print("Paraphrasing of region [%i:%i]" % (edit_start, edit_end))
                    sub_chunks = (
                        chunk_max(chunk_to_edit, max_chunk_size=500)
                        if len(chunk_to_edit) > 500
                        else [chunk_to_edit]
                    )
                    edit["chunk_indices"] = list(
                        range(
                            len(paraphrase_chunks),
                            len(paraphrase_chunks) + len(sub_chunks),
                        )
                    )
                    paraphrase_chunks.extend(sub_chunks)
                edits.append(edit)

            paraphrases = self.get_paraphrases(
                paraphrase_chunks, temperature=1.0 if stuck else 0.8
            )
            for edit in edits:
                if "chunk_indices" in edit:
                    edit["edited"] = " ".join(paraphrases[i] for i in edit["chunk_indices"])

            # We only keep the edits that actually reduce the alignment of their window with
            # the original text, so that a single bad edit (e.g. a near-verbatim paraphrase)
            # does not spoil the whole batch. These local alignments are cheap since the
            # windows are short.
            applied_edits = []
            for edit in edits:
                score_before = self.aligner.get_largest_region_score(
                    initial_text_nobreaks, edit["original"]
                )
                score_after = self.aligner.get_largest_region_score(
                    initial_text_nobreaks, edit["edited"]
                )
                if score_after < score_before:
                    applied_edits.append(edit)
                else:
                    print(
                        "WARNING: edit of region [%i:%i] did not reduce its score (%.1f -> %.1f), dropping it"
                        % (edit["start"], edit["end"], score_before, score_after)
                    )

            # We construct the new text by replacing the edited windows (from the last to
            # the first, so that the offsets of the remaining windows stay valid)
            new_text = cur_text
            for edit in sorted(applied_edits, key=lambda e: e["start"], reverse=True):
                new_text = (
                    new_text[: edit["start"]]
                    + " "
                    + edit["edited"]
                    + " "
                    + new_text[edit["end"] :]
                )
            new_text = re.sub(r"\s+", " ", new_text).strip()

            if debug:
                print("After edit:", new_text)

            # We compute the oracle score of the new text compared to the original text
            new_score, new_top_start, new_top_end = self._top_region(
                initial_text_nobreaks, new_text
            )
            print("==> Region score after edit: %.1f" % new_score)
            step_nr += 1

            # If no edit could be applied or the score increased, we skip the step and keep
            # the previous text. If the score is unchanged, the edit is kept (it did not hurt,
            # and typically broke a region tied with another one, e.g. a header repeated on
            # every page), but still counts as a step without progress, so that repeated
            # no-op steps trigger a change of strategy.
            if not applied_edits or new_score > cur_score:
                if new_score > cur_score:
                    print("WARNING: Region score increased after edit, skipping step")
                else:
                    print("WARNING: No effective edit could be applied, skipping step")
                nb_consecutive_skips += 1
                top_start, top_end = regions[0][0], regions[0][1]
            elif new_score == cur_score:
                print("WARNING: Region score unchanged after edit, keeping edit anyway")
                nb_consecutive_skips += 1
                cur_text = new_text
                top_start, top_end = new_top_start, new_top_end
            else:
                nb_consecutive_skips = 0
                cur_score = new_score
                cur_text = new_text

            # If several consecutive steps made no progress, we mechanically break the
            # largest aligned region by inserting a boilerplate segment at a random
            # position inside it.
            if nb_consecutive_skips >= 4:
                print("WARNING: too many consecutive skips, inserting boilerplate")
                cur_text = self._insert_boilerplate(cur_text, top_start, top_end)
                cur_text = re.sub(r"\s+", " ", cur_text).strip()
                cur_score = self.aligner.get_largest_region_score(
                    initial_text_nobreaks, cur_text
                )
                print("==> Region score after boilerplate insertion: %.1f" % cur_score)
                nb_consecutive_skips = 0

        if cur_score >= self.min_oracle_score:
            raise RuntimeError(
                "Example pair still above threshold after %i paraphrasing/permutation attempts, aborting."
                % max_nb_attempts
            )

        print(
            "Finished editing doc %s after %i paraphrasing steps. Final score: %.1f"
            % (doc["id"], step_nr - 1, cur_score)
        )
        if debug:
            print("Final text:", cur_text)

        result = {
            "text1": initial_text,
            "text2": cur_text,
            "pair_type": "negative",
            "score": cur_score,
            "meta": {k: v for k, v in doc.items() if k not in {"text"}},
        }
        return result

    def continue_negative(
        self, doc_incr: int, max_nb_attempts=150, debug=False
    ) -> dict:
        """Assuming self.corpus is a corpus of negative examples, continue editing the text through
        paraphrasing."""

        doc = self.corpus.data[doc_incr]

        initial_text = str(doc["source_text"])
        initial_text_nobreaks = re.sub(r"\s+", " ", initial_text).strip()

        print("Working on text", doc["source_doc_id"], flush=True)
        if debug:
            print("Original text:", initial_text_nobreaks)

        cur_score = doc["oracle_score"]
        cur_text = str(doc["text"])

        step_nr = 1
        while step_nr <= max_nb_attempts and cur_score >= self.min_oracle_score:
            print("STEP %i:" % (step_nr), flush=True)

            # We identify the region of the text that will have the maximum impact on the oracle score if edited
            edit_start, edit_end = self._get_region_to_edit(
                initial_text_nobreaks, cur_text, max_chunk_size=400
            )

            print("Paraphrasing of region [%i:%i]" % (edit_start, edit_end))
            chunk_to_edit = cur_text[edit_start:edit_end]
            edited_chunk = self.get_paraphrase(chunk_to_edit)

            # We construct the new text by replacing the selected region with the edited chunk
            parts = [
                cur_text[:edit_start],
                edited_chunk,
                cur_text[edit_end:],
            ]
            new_text = " ".join(parts)
            new_text = re.sub(r"\s+", " ", new_text).strip()

            if debug:
                print("After edit:", new_text)

            # We compute the oracle score of the new text compared to the original text
            new_score = self.aligner.get_largest_region_score(
                initial_text_nobreaks, new_text
            )
            print("==> Region score after edit: %.1f" % new_score)
            step_nr += 1

            # If the new score is higher than the current score, we skip this edit, but add a boilerplate
            # segment somewhere in the region that was edited, to reduce the score in the next step.
            if new_score > cur_score:
                print(
                    "WARNING: Region score increased after edit, skipping step, and adding boilerplate"
                )
                cur_text = self._insert_boilerplate(cur_text, edit_start, edit_end)
                continue
            else:
                cur_score = new_score
                cur_text = new_text

        if cur_score >= self.min_oracle_score:
            raise RuntimeError(
                "Example pair still above threshold after %i paraphrasing/permutation attempts, aborting."
                % max_nb_attempts
            )

        print(
            "Finished editing doc %s after %i paraphrasing steps. Final score: %.1f"
            % (doc["source_doc_id"], step_nr - 1, cur_score)
        )
        if debug:
            print("Final text:", cur_text)

        result = {
            "text1": initial_text,
            "text2": cur_text,
            "score": cur_score,
            "meta": {"id": doc["source_doc_id"]},
        }
        return result

    @staticmethod
    def _insert_boilerplate(text: str, region_start: int, region_end: int) -> str:
        """Insert a random boilerplate segment at a word boundary chosen at random within
        the region [region_start:region_end] of the text. If the region contains no word
        boundary (e.g. a long URL or formula), the segment is inserted after a punctuation
        character inside the region, or at a random position as a last resort."""
        segment_to_insert = np.random.choice(BOILERPLATE_SEGMENTS)
        insertion_point = np.random.randint(region_start, max(region_end, region_start + 1))
        space_point = text.find(" ", insertion_point, region_end)
        if space_point != -1:
            insertion_point = space_point
        else:
            m = re.search(r"[./_\-=&?,;:)\]]", text[insertion_point:region_end])
            if m:
                insertion_point = insertion_point + m.end()
        return text[:insertion_point] + " " + segment_to_insert + " " + text[insertion_point:]

    def _top_region(self, initial_text: str, edited_text: str) -> Tuple[float, int, int]:
        """Return (score, start, end) of the region of the edited text that best aligns
        with the initial text, or (0.0, 0, 0) if there is no aligned region."""
        alignment_result = self.aligner.run(initial_text, edited_text)
        if not alignment_result.regions:
            return (0.0, 0, 0)
        largest_region = max(alignment_result.regions, key=lambda r: r["score"])
        return (largest_region["score"], largest_region["start2"], largest_region["end2"])

    def _find_regions_to_edit(
        self,
        initial_text: str,
        edited_text: str,
        min_score: float,
        max_regions: int = 32,
    ) -> List[Tuple[int, int, float]]:
        """Find up to max_regions non-overlapping regions of the edited text that align
        with the initial text with a score of at least min_score, as a list of
        (start, end, score) tuples sorted by decreasing score.

        The aligner only returns the single best local alignment, so we iteratively cut
        the best region out of the edited text (keeping a map back to the original
        offsets) and re-run the alignment on the remainder.
        """
        masked_text = edited_text
        offset_map = np.arange(len(edited_text))
        separator_map = np.full(len(_MASK_SEPARATOR), -1)
        regions: List[Tuple[int, int, float]] = []
        while len(regions) < max_regions:
            score, start, end = self._top_region(initial_text, masked_text)
            if score < min_score or end <= start:
                break
            original_offsets = offset_map[start:end]
            original_offsets = original_offsets[original_offsets >= 0]
            if len(original_offsets) == 0:
                break
            regions.append(
                (int(original_offsets[0]), int(original_offsets[-1]) + 1, score)
            )
            masked_text = masked_text[:start] + _MASK_SEPARATOR + masked_text[end:]
            offset_map = np.concatenate(
                (offset_map[:start], separator_map, offset_map[end:])
            )
        return regions

    def _get_region_to_edit(
        self,
        initial_text: str,
        edited_text: str,
        max_chunk_size: Optional[int] = None,
    ) -> Tuple[int, int]:
        """Identify a region of the edited text that fullfills the following criteria:
        - it belongs to the region of highest similarity with the initial text
        - it covers at most max_chunk_size characters of that region (if specified)
        - it is expanded outward to sentence boundaries, so that the partial sentences
          at the edges of the aligned region are edited as well.

        Returns:
            A tuple (start, end) representing the start and end indices of the region to edit.
        """
        _, region_start, region_end = self._top_region(initial_text, edited_text)
        if region_start >= region_end:
            return (region_start, region_start)
        return self._select_window(edited_text, region_start, region_end, max_chunk_size)

    def _select_window(
        self,
        text: str,
        region_start: int,
        region_end: int,
        max_chunk_size: Optional[int] = None,
    ) -> Tuple[int, int]:
        """Select a window to edit inside the aligned region [region_start:region_end]: the
        full region if it fits in max_chunk_size (or if no size is given), otherwise a
        random sub-window of max_chunk_size characters. The window is then expanded
        outward to sentence boundaries."""
        if max_chunk_size is not None and region_end - region_start > max_chunk_size:
            edit_start = np.random.randint(region_start, region_end - max_chunk_size + 1)
            edit_end = edit_start + max_chunk_size
        else:
            edit_start, edit_end = region_start, region_end
        return self._expand_to_sentence_boundaries(text, edit_start, edit_end)

    @staticmethod
    def _expand_to_sentence_boundaries(
        text: str, start: int, end: int, max_expansion: int = 150
    ) -> Tuple[int, int]:
        """Expand the span [start:end] outward to the closest sentence boundaries, looking
        at most max_expansion characters beyond each end. If no sentence boundary is found
        within that distance, the span is only expanded to the closest word boundaries.

        Expanding outward (rather than shrinking inward) guarantees that the whole aligned
        region is covered by the edit, including the partial sentences at its edges which
        would otherwise keep aligning with the original text."""

        # Start: nothing to do if we are already right after a sentence boundary
        if start > 0 and not re.search(r"[.!?]\s*$", text[max(0, start - 2) : start]):
            left_limit = max(0, start - max_expansion)
            boundaries = list(re.finditer(r"[.!?]\s+", text[left_limit:start]))
            if boundaries:
                start = left_limit + boundaries[-1].end()
            else:
                last_space = text.rfind(" ", left_limit, start)
                if last_space != -1:
                    start = last_space + 1

        # End: nothing to do if we are already right after a sentence boundary
        if end < len(text) and not re.search(r"[.!?]\s*$", text[max(0, end - 2) : end]):
            right_limit = min(len(text), end + max_expansion)
            m = re.search(r"[.!?]", text[end:right_limit])
            if m:
                end = end + m.end()
            else:
                next_space = text.find(" ", end, right_limit)
                if next_space != -1:
                    end = next_space

        return (start, end)

    @staticmethod
    def _merge_windows(windows: List[Tuple[int, int]]) -> List[Tuple[int, int]]:
        """Sort the windows by position and merge the ones that overlap or touch."""
        merged: List[Tuple[int, int]] = []
        for start, end in sorted(windows):
            if merged and start <= merged[-1][1]:
                merged[-1] = (merged[-1][0], max(merged[-1][1], end))
            else:
                merged.append((start, end))
        return merged

    def get_paraphrase(self, chunk: str) -> str:
        """Use the LLM to generate a paraphrase of a single chunk of text (see
        get_paraphrases)."""
        return self.get_paraphrases([chunk])[0]

    def get_paraphrases(self, chunks: List[str], temperature: float = 0.8) -> List[str]:
        """Use the LLM to generate paraphrases of the input chunks of text in a single
        batch, by prompting it with instructions to produce a lightly edited version of
        each input text that retains the same meaning but with slightly different words.
        Chunks whose paraphrase is implausibly short or long are returned unchanged."""

        if self.model is None:
            raise RuntimeError("LLM model not initialized for paraphrasing.")
        if not chunks:
            return []

        # We set the sampling parameters
        import vllm

        sampling_params = vllm.SamplingParams(
            temperature=temperature, top_p=0.8, top_k=50, max_tokens=600, n=1
        )

        # We add the chunks to the prompt, one conversation per chunk
        conversations = [
            [{"role": "user", "content": PROMPT_TEMPLATE.format(text=chunk)}]
            for chunk in chunks
        ]

        # We call the model (outputs are returned in the same order as the inputs)
        outputs = self.model.chat(
            conversations,
            sampling_params,
            chat_template_kwargs={"enable_thinking": False},
        )

        # We extract the model's responses.
        paraphrases = []
        for chunk, output in zip(chunks, outputs):
            response = output.outputs[0].text.strip()
            if len(response) < len(chunk) * 0.3:
                print("WARNING: Paraphrased text is too short. Using original chunk.")
                paraphrases.append(chunk)
            elif len(response) > len(chunk) * 2.5:
                print("WARNING: Paraphrased text is too long. Using original chunk.")
                print("ORIGINAL:", chunk)
                print("PARAPHRASED:", response)
                paraphrases.append(chunk)
            else:
                paraphrases.append(response)

        return paraphrases

    def permute_chunks(self, text):
        """Randomly permute the order of a few chunks of the input text."""
        # We sample chunk proportions from a Dirichlet distribution to determine the relative sizes of the chunks

        nb_chunks = np.random.randint(2, 9)  # Split into 2 to 8 chunks
        chunk_proportions = np.random.dirichlet(np.ones(nb_chunks), size=1)[0]

        # We use the chunk_proportion method to split the text into chunks of approximately
        # the specified relative sizes
        chunks = chunk_proportion(text, chunk_proportions=chunk_proportions)

        # If the text could not be split into at least two chunks (e.g. a single word),
        # a permutation cannot change anything, so we return the text as is.
        if len(chunks) < 2:
            print("WARNING: Could not split text into at least two chunks for permutation.")
            return text

        print(
            "Permuting %i chunks of sizes: %s (target proportions: %s)"
            % (len(chunks), [len(c) for c in chunks], str(chunk_proportions))
        )

        # We randomly permute the order of the chunks, making sure that the order actually
        # changes (otherwise, the permutation would be a no-op and the step would be wasted).
        original_order = list(chunks)
        for _ in range(10):
            np.random.shuffle(chunks)
            if chunks != original_order:
                break
        else:
            chunks = original_order[1:] + original_order[:1]

        return " ".join(chunks)


# Boundary patterns used to split a text into units, from strongest to weakest: sentence
# boundaries, then "soft" boundaries (clause punctuation, table cell separators, newlines),
# then plain whitespace. Weaker patterns are only used when the stronger ones do not yield
# enough units (e.g. for flattened tables, formulas or reference lists without sentences).
_UNIT_BOUNDARIES = [
    r"(?<=[.!?]) +",
    r"(?<=[.!?,;:|]) +|\s*\n\s*",
    r"\s+",
]


def split_units(
    text: str, min_units: int = 2, max_unit_size: Optional[int] = None
) -> List[str]:
    """Split the input text into non-empty units, preferably at sentence boundaries.

    If the sentence-level split yields fewer than min_units units, or if some units are
    longer than max_unit_size (when specified), those units are further split using
    progressively weaker boundaries (clause punctuation, cell separators, whitespace).
    Units that already satisfy the constraints are left untouched, so regular prose keeps
    its sentence-level granularity.
    """
    units = [text] if text else []
    for pattern in _UNIT_BOUNDARIES:
        too_few = len(units) < min_units
        new_units = []
        for unit in units:
            oversized = max_unit_size is not None and len(unit) > max_unit_size
            if too_few or oversized:
                new_units.extend(u for u in re.split(pattern, unit) if u)
            else:
                new_units.append(unit)
        units = new_units
        if len(units) >= min_units and (
            max_unit_size is None or all(len(u) <= max_unit_size for u in units)
        ):
            break
    return units


def chunk_min(text, min_chunk_size=400):
    """Split the input text into chunks of a specified size, ensuring that splits occur
    at sentence boundaries when possible.

    Each chunk should be at least min_chunk_size characters long.
    """
    if min_chunk_size >= len(text):
        raise ValueError(
            "min_chunk_size must be smaller than the length of the input text."
        )

    # Units much longer than the chunk size (typically sentence-free blocks such as tables)
    # are sub-split at weaker boundaries; ordinary long sentences are left intact.
    sentences = split_units(text, max_unit_size=3 * min_chunk_size)
    chunks = []
    current_chunk = ""
    for sentence in sentences:
        current_chunk += " " + sentence if current_chunk else sentence
        if len(current_chunk) > min_chunk_size:
            chunks.append(current_chunk.strip())
            current_chunk = ""

    if current_chunk:
        if chunks:
            chunks[-1] += " " + current_chunk.strip()
        else:
            print("WARNING: single chunk of size", len(current_chunk))
            chunks.append(current_chunk.strip())

    return chunks


def chunk_max(text, max_chunk_size=400):
    """Split the input text into chunks of a specified size, ensuring that splits occur
    at sentence boundaries when possible.

    Each chunk should be at most max_chunk_size characters long.
    """
    sentences = split_units(text, max_unit_size=max_chunk_size)
    chunks = []
    current_chunk = ""
    for sentence in sentences:
        new_chunk = current_chunk + " " + sentence if current_chunk else sentence
        if current_chunk and len(new_chunk) > max_chunk_size:
            chunks.append(current_chunk.strip())
            current_chunk = sentence
        else:
            current_chunk = new_chunk

    if current_chunk:
        chunks.append(current_chunk.strip())

    return chunks


def chunk_proportion(text, chunk_proportions: List[float]):
    """Split the input text into chunks, where the approximate size of each chunk is
    determined by the corresponding value in chunk_proportions. The method ensures that
    splits occur at sentence boundaries when possible.

    Args:
        text: The input text to be chunked.
        chunk_proportions: A list of relative sizes for each chunk. The values should sum to 1.

    Returns:
        A list of text chunks corresponding to the specified relative sizes.

    """
    if not np.isclose(sum(chunk_proportions), 1.0, atol=1e-2):
        raise ValueError("The values in chunk_proportions should sum to 1.")

    units = split_units(text, min_units=len(chunk_proportions))
    total_length = len(text)

    # Cut points (in characters) between consecutive chunks; each unit is assigned to
    # the chunk whose cut point lies beyond the unit's midpoint.
    cut_points = np.cumsum(chunk_proportions) * total_length
    chunks: List[str] = [""] * len(chunk_proportions)
    position = 0
    for unit in units:
        midpoint = position + len(unit) / 2
        chunk_idx = min(int(np.searchsorted(cut_points, midpoint)), len(chunks) - 1)
        chunks[chunk_idx] = (chunks[chunk_idx] + " " + unit) if chunks[chunk_idx] else unit
        position += len(unit) + 1

    return [c.strip() for c in chunks if c.strip()]


def create_negative_samples(
    indexed_samples_path: str,
    min_oracle_score: float = 100,
    output_path: str = "negative_samples_100.jsonl",
    overwrite_existing: bool = False,
    use_llm: bool = True,
):
    """Create negative samples (in relation to a corpus of indexed texts) and save them
    to a JSONL file.

    The method continuously samples negative examples using the NegativeExampleGenerator
    and appends them to the output file.

    Args:
        indexed_samples_path: Path to the JSONL file containing the indexed samples
      (the corpus from which the negative examples will be generated).
        min_oracle_score: Minimum oracle score required for a sample to be considered
        a valid negative example.
        output_path: Path to the JSONL file where the generated negative samples
      will be saved.
        overwrite_existing: If True, the method will overwrite the output
        use_llm: whether to use an LLM for paraphrasing, or just rely on permutations
      file if it already exists. If False, it will append to the existing file.

    """
    corpus = Corpus(indexed_samples_path)

    if use_llm:
        neg_gen = NegativeExampleGenerator(corpus, min_oracle_score=min_oracle_score)
    else:
        neg_gen = NegativeExampleGenerator(
            corpus, llm_model=None, min_oracle_score=min_oracle_score
        )

    if os.path.exists(output_path) and overwrite_existing:
        os.remove(output_path)
    print("Storing negative samples in %s" % output_path)

    while True:
        print("Start sampling negative example pair")
        try:
            neg_example = neg_gen.sample_negative()
            result = {
                "text": neg_example["text2"],
                "source_doc_id": neg_example["meta"]["id"],
                "source_text": neg_example["text1"],
                "type": "negative",
                "oracle_score": neg_example["score"],
            }

            with filelock.FileLock(f"{output_path}.lock"):
                with open(output_path, "a") as f:
                    f.write(orjson.dumps(result).decode("utf-8") + "\n")
                    print("DONE")

        except Exception as e:
            print(f"Error occurred while sampling negative example: {e}")


def continue_negative_samples(
    input_negative_samples_path: str,
    min_oracle_score: float = 1000,
    output_path: str = "negative_samples_1000.jsonl",
    overwrite_existing: bool = False,
    max_nb_attempts: int = 150,
):
    """Create negative samples (in relation to a corpus of indexed texts) and save them
    to a JSONL file.

    The method continuously samples negative examples using the NegativeExampleGenerator
    and appends them to the output file.

    Args:
        input_negative_samples_path: Path to the JSONL file containing the existing negative samples
      (the corpus from which the negative examples will be generated).
        min_oracle_score: Minimum oracle score required for a sample to be considered
        a valid negative example.
        output_path: Path to the JSONL file where the generated negative samples
      will be saved.
        max_nb_attempts: Maximum number of attempts to generate a valid negative example.
        overwrite_existing: If True, the method will overwrite the output
      file if it already exists. If False, it will append to the existing file.

    """
    corpus = Corpus(input_negative_samples_path)

    neg_gen = NegativeExampleGenerator(corpus, min_oracle_score=min_oracle_score)

    if os.path.exists(output_path) and overwrite_existing:
        os.remove(output_path)
    print("Storing negative samples in %s" % output_path)

    source_doc_ids_already_done = set()
    if not overwrite_existing and os.path.exists(output_path):
        with open(output_path, "r") as f:
            for line in f:
                try:
                    sample = orjson.loads(line)
                    source_doc_ids_already_done.add(sample["source_doc_id"])
                except Exception as e:
                    print(f"Error occurred while reading existing output file: {e}")

    doc_indices_to_do = list(range(len(corpus.data)))
    random.shuffle(doc_indices_to_do)

    for doc_idx in doc_indices_to_do:
        if corpus.data[doc_idx]["source_doc_id"] in source_doc_ids_already_done:
            print(
                f"Skipping doc {corpus.data[doc_idx]['source_doc_id']} as it is already done."
            )
            continue

        print("Continue editing negative example pair")
        try:
            neg_example = neg_gen.continue_negative(
                doc_idx, max_nb_attempts=max_nb_attempts
            )
            result = {
                "text": neg_example["text2"],
                "source_doc_id": neg_example["meta"]["id"],
                "source_text": neg_example["text1"],
                "type": "negative",
                "oracle_score": neg_example["score"],
            }

            with filelock.FileLock(f"{output_path}.lock"):
                with open(output_path, "a") as f:
                    f.write(orjson.dumps(result).decode("utf-8") + "\n")
                    print("DONE")

                with open(output_path, "r") as f:
                    for line in f:
                        try:
                            sample = orjson.loads(line)
                            source_doc_ids_already_done.add(sample["source_doc_id"])
                        except Exception as e:
                            print(
                                f"Error occurred while reading existing output file: {e}"
                            )

        except Exception as e:
            print(f"Error occurred while sampling negative example: {e}")


